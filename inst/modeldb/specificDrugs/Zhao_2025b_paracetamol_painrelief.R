Zhao_2025b_paracetamol_painrelief <- function() {
  description <- paste(
    "Direct sigmoid Emax (Hill) pharmacodynamic model relating the plasma",
    "concentration of paracetamol (acetaminophen) to the pain relief score",
    "(0-10 scale, higher = more relief) in adults with chronic pain (Zhao 2025,",
    "the PD layer of a GastroPlus parent-metabolite PBPK/PD model for",
    "MASLD-related populations). The PD relationship was benchmarked against",
    "the plasma concentration / pain relief data of Shinoda 2007 (Japanese",
    "chronic-pain patients given a 1 g oral tablet). Only this PD layer is",
    "reproduced here: the paracetamol and five-metabolite PBPK layers are",
    "GastroPlus platform models whose tissue partition coefficients (Lukacova",
    "method), organ volumes and blood flows, per-tissue enzyme amounts and",
    "MASLD-population physiologies are software-database outputs that the",
    "paper never prints, so they are not reproducible from the publication (see",
    "the vignette 'Assumptions and deviations'). Paracetamol plasma",
    "concentration is therefore supplied by the user as the canonical",
    "effect-site covariate CEFFECT rather than generated by a PK model in this",
    "file. No inter-individual variability and no residual-error model are",
    "reported, so both are absent / fixed at zero.",
    sep = " "
  )
  reference <- paste(
    "Zhao S, Zhang L (2025).",
    "Evaluation of the PK/PD Changes on MASLD-Related Population - An Example",
    "From Simultaneous Acetaminophen Parent-Metabolite PBPK/PD Modeling.",
    "CPT Pharmacometrics Syst Pharmacol 15(1):e70161.",
    "doi:10.1002/psp4.70161.",
    sep = " "
  )
  vignette <- "Zhao_2025b_paracetamol_painrelief"
  units <- list(
    time = "h",
    dosing = "(not applicable; plasma concentration is supplied as the CEFFECT covariate, not as a dose record)",
    concentration = "ug/mL (paracetamol plasma concentration via CEFFECT; the PD output score is a 0-10 pain relief score)"
  )

  covariateData <- list(
    CEFFECT = list(
      description = "Paracetamol (acetaminophen) plasma concentration (ug/mL), supplied as the driver of the direct sigmoid Emax pain relief response",
      units = "ug/mL",
      type = "continuous",
      reference_category = NULL,
      notes = paste(
        "Member of the canonical effect-site PD driver family CEFFECT; here the",
        "biophase is taken to be PLASMA: Zhao 2025 Results ('PK/PD Simulation on",
        "MASLD-Related Population') states 'Predicted APAP plasma concentrations",
        "were related to pain relief scores using a Sigmoid Emax model'. The",
        "supplement ('The exploration of the PK-PD model that links the",
        "appropriate effect-site species to analgesia') justifies plasma as a",
        "surrogate for unbound brain exposure: the PBPK-simulated plasma and",
        "unbound brain profiles peak at 0.89 h and 0.96 h (brain Kp 1.519),",
        "with Cmax about 10000 ng/mL in plasma and 7500 ng/mL unbound in brain",
        "(Figure S7). In the source study CEFFECT is the plasma profile predicted",
        "by the authors' GastroPlus PBPK model for each population (normal",
        "weight, overweight, obese, non-NAFLD, NAFLD, NASH, healthy, cirrhosis",
        "Child-Pugh A/B/C). That PBPK model is NOT reproduced in this file. Its",
        "printed benchmark aggregates, from noncompartmental analysis of the",
        "observed intravenous studies, are Vss 68.46 L and total CL 21.18 L/h",
        "(Zhao 2025 Results). For downstream simulation users supply CEFFECT",
        "from a paracetamol population PK model in mg/L (= ug/mL) or from",
        "observed plasma concentrations; units must be ug/mL because EC50 is."
      ),
      source_name = "(none; plasma concentration is a PBPK-predicted profile, not a named data column in the source)"
    )
  )

  population <- list(
    species = "human",
    n_subjects = NA_integer_,
    n_studies = 1L,
    age_range = "adults (not reported in Zhao 2025)",
    weight_range = "not reported",
    sex_female_pct = NA_real_,
    race_ethnicity = "Japanese (Shinoda 2007 benchmark cohort)",
    disease_state = "chronic pain (PD benchmark cohort); PD simulated for normal-weight, overweight, obese, NAFLD, NASH and cirrhosis Child-Pugh A/B/C virtual populations",
    dose_range = "1 g oral paracetamol tablet, single dose (Shinoda 2007 benchmark, Zhao 2025 Table S3)",
    regions = "Japan (benchmark data)",
    notes = paste(
      "Zhao 2025 Methods ('The PK/PD Model on the MASLD-Related Population'):",
      "'The PD here refers to the pain relief score, which is in the range of",
      "0-10. The PK/PD data, which was done on chronic pain patients from",
      "Shinoda's report, was used as the benchmark.' Zhao 2025 does not restate",
      "the size or demographics of the Shinoda 2007 cohort (Shinoda S et al.,",
      "Biol Pharm Bull 2007;30(1):157-161), so n_subjects, sex and weight are",
      "left unreported here rather than taken from that paper, which is not",
      "part of the source set. The PD parameters were obtained with the",
      "GastroPlus PD module; the paper calls them 'the individual PD",
      "parameters' and reports no standard errors."
    )
  )

  ini({
    # ------------------------------------------------------------------
    # Zhao 2025 Results, 'PK/PD Simulation on MASLD-Related Population':
    # 'Predicted APAP plasma concentrations were related to pain relief
    # scores using a Sigmoid Emax model, also known as Hill equations ...
    # Pain relief scores were treated as continuous variables on a scale of
    # 0-10. The individual PD parameters are: E0 = 0, EC50 = 1.612 ug/mL,
    # Emax = 3.898, Hill coefficient = 1.36, where E0 is the worst pain
    # relief possible, Emax represents the maximum pain relief score'.
    #
    #   score = E0 + Emax * C^hill / (EC50^hill + C^hill)
    #
    # No IIV, standard error or residual-error model is reported for the
    # PD layer, so no eta is declared and the residual SD is fixed at zero.
    # ------------------------------------------------------------------

    e0 <- fixed(0)
    label("Baseline pain relief score with no drug (score units, 0-10 scale)")
    # Zhao 2025 Results: 'E0 = 0 ... where E0 is the worst pain relief
    # possible'. Fixed: the bottom of the 0-10 scale, not an estimate.

    lemax <- log(3.898)
    label("Log of Emax, maximum drug-attributable pain relief score (score units)")
    # Zhao 2025 Results: 'Emax = 3.898'.

    lec50 <- log(1.612)
    label("Log of EC50, plasma paracetamol concentration giving half of Emax (ug/mL)")
    # Zhao 2025 Results: 'EC50 = 1.612 ug/mL'.

    lhill <- log(1.36)
    label("Log of the Hill coefficient of the sigmoid Emax function (unitless)")
    # Zhao 2025 Results: 'Hill coefficient = 1.36'.

    addSd <- fixed(0)
    label("Additive residual SD on the pain relief score (score units; ZERO - no residual-error model is reported by the source)")
  })

  model({
    # 1. Paracetamol plasma concentration for this record, in ug/mL,
    #    supplied through the canonical CEFFECT covariate column. Zhao 2025
    #    relates the score directly to plasma concentration, with no effect
    #    compartment.
    conc <- CEFFECT

    # 2. Typical-value PD parameters (no IIV reported).
    emax <- exp(lemax)
    ec50 <- exp(lec50)
    hill <- exp(lhill)

    # 3. Direct sigmoid Emax on plasma concentration.
    score <- e0 + emax * conc^hill / (ec50^hill + conc^hill)

    # 4. Observation. The additive residual SD is fixed at zero because the
    #    source reports no residual-error model; users refitting this model
    #    to individual pain relief data should free addSd.
    score ~ add(addSd)
  })
}
