Marier_2011_cenicriviroc_hiv1rna <- function() {
  description <- paste(
    "Static exposure-response Emax model relating average steady-state plasma",
    "cenicriviroc concentration to the day-11 change from baseline in plasma",
    "HIV-1 RNA, in HIV-1-infected, antiretroviral treatment-experienced,",
    "CCR5-antagonist-naive adults given 10 days of once-daily oral monotherapy",
    "(Marier 2011). The drug is identified throughout the source only by its",
    "Tobira Therapeutics development code TBR-652 (also TAK-652); the INN",
    "cenicriviroc was assigned later, and this file uses the INN per the",
    "nlmixr2lib naming policy. Cenicriviroc is a dual CCR5 / CCR2 antagonist.",
    "The model is:",
    "dviralLoad = emax * CSS_CVC / (ic50 + CSS_CVC),",
    "with emax = -1.43 log10 copies/mL and ic50 = 13.1 ng/mL. It is a SIMPLE",
    "(hyperbolic, non-sigmoidal) Emax model with NO baseline / placebo",
    "intercept term: the authors tested sigmoidal (gamma) and linear",
    "alternatives and selected this form by AIC, and the fitted curve in the",
    "source's Figure 3 passes through the origin, where the placebo subjects",
    "sit. There is NO structural pharmacokinetic component -- the source",
    "characterised cenicriviroc PK by noncompartmental analysis only, so the",
    "driving exposure is supplied as the covariate CSS_CVC (an NCA-derived",
    "per-subject average steady-state concentration, AUC0-24 / 24 h), not",
    "generated by dose events. The source reports no inter-individual",
    "variability and no residual error for this fit, only standard errors on",
    "the two parameters (0.138 log10 copies/mL on Emax and 6.53 ng/mL on",
    "IC50), so the model returns the deterministic curve. Companion model file",
    "Marier_2011_cenicriviroc_mcp1.R carries the paper's second, independently",
    "fitted Emax model, for the CCR2-blockade biomarker MCP-1.",
    sep = " "
  )

  reference <- paste(
    "Marier JF, Trinh M, Pheng LH, Palleja SM, Martin DE.",
    "Pharmacokinetics and pharmacodynamics of TBR-652, a novel CCR5",
    "antagonist, in HIV-1-infected, antiretroviral treatment-experienced,",
    "CCR5 antagonist-naive patients.",
    "Antimicrob Agents Chemother. 2011;55(6):2768-2774.",
    "doi:10.1128/AAC.00713-10. PMCID PMC3101382.",
    "PK/PD model form is in Methods 'Pharmacokinetic/pharmacodynamic",
    "modeling' (p. 2770); the parameter estimates and their standard errors",
    "are in Results (p. 2772) and are restated in the Discussion (p. 2773);",
    "the fitted curve and the individual data it was fit to are Figure 3",
    "(p. 2773).",
    "Companion model file from the same paper:",
    "modellib('Marier_2011_cenicriviroc_mcp1').",
    sep = " "
  )

  vignette <- "Marier_2011_cenicriviroc"

  units <- list(
    time          = "h",
    dosing        = "not applicable (static exposure-response model; cenicriviroc exposure enters through the covariate CSS_CVC rather than through rxode2 dose events)",
    concentration = "log10 copies/mL (the modelled observation dviralLoad is the day-11 CHANGE FROM BASELINE in plasma HIV-1 RNA, NOT a drug concentration; the driving covariate CSS_CVC is the average steady-state cenicriviroc plasma concentration in ng/mL)"
  )

  covariateData <- list(
    CSS_CVC = list(
      description        = "Individual average steady-state plasma concentration (Css) of cenicriviroc (TBR-652) on day 10 of once-daily oral dosing, carried as the per-subject exposure metric that drives the Emax term.",
      units              = "ng/mL",
      type               = "continuous",
      reference_category = NULL,
      notes              = paste(
        "Not an observation and not a model output: Marier 2011 derived Css by noncompartmental analysis in WinNonlin 5.2 as AUC0-24 / 24 h from the day-10 intensive profile (Methods 'Pharmacokinetics', p. 2769). That identity is exact in the paper's own Table 2 and is asserted in the validation vignette: 382.0/24 = 15.92, 1245/24 = 51.88, 1916/24 = 79.83, 2659/24 = 110.8 and 7272/24 = 303.0 ng/mL for the 25, 50, 75, 100 and 150 mg QD cohorts.",
        "Cohort MEAN Css (with CV%) from Table 2 (p. 2772): 15.92 (52.8%) at 25 mg, 51.89 (40.4%) at 50 mg, 79.82 (30.6%) at 75 mg, 110.8 (52.8%) at 100 mg and 303.0 (36.8%) at 150 mg QD. The model was fit to INDIVIDUAL Css values, which span roughly 0 to 490 ng/mL across Figure 3.",
        "PLACEBO subjects carry CSS_CVC = 0, which is how they enter the fit: Figure 3 plots them as open circles on the y-axis, and the model returns exactly 0 there because it has no intercept term. Set CSS_CVC = 0 to simulate placebo.",
        "There is no PK model in this paper to generate the column with -- the PK analysis was noncompartmental only. For new simulations either supply Css directly, or compute it as Dose / (CL/F * 24 h) using the cohort mean CL/F values in Table 2 (81.31, 49.26, 42.17, 48.06 and 22.95 L/h at 25, 50, 75, 100 and 150 mg QD). Note that CL/F is NOT constant across the dose range: exposure rose more than proportionally at 150 mg, and two subjects dosed in Argentina showed more than 2-fold higher exposure than the rest of the 100 mg cohort, which the authors attribute to a possible high-fat food effect (Results, p. 2771).",
        "Steady state was confirmed before sampling: Helmert contrasts on the day-8, -9 and -10 troughs were not significant at alpha = 0.05 for any dose level, so day-10 parameters are steady-state parameters (Results, p. 2771).",
        "Total, not unbound. Compare against the paper's in-vitro-estimated therapeutic concentration of 2 ng/mL and the fitted IC50 of 13.1 ng/mL on the same total-concentration basis."
      ),
      source_name        = "Css (average concentration under steady-state conditions)"
    )
  )

  # Baseline characteristics that Marier 2011 tabulates for the study
  # population (Table 1, p. 2770) but that the Emax model does not use --
  # the PK/PD analysis regressed the day-11 change from baseline on Css
  # alone, with no covariate screen reported. Documentation only.
  covariatesDataExcluded <- list(
    WT = list(
      description        = "Body weight at baseline.",
      units              = "kg",
      type               = "continuous",
      reference_category = NULL,
      notes              = "Tabulated per cohort in Table 1 (overall mean 79.81 kg, SD 17.08; cohort means 69.50-93.87 kg) but never entered into the PK/PD model. Marier 2011 reports no covariate analysis on the Emax parameters.",
      source_name        = "Mean wt (kg) (SD)"
    ),
    AGE = list(
      description        = "Age at baseline.",
      units              = "years",
      type               = "continuous",
      reference_category = NULL,
      notes              = "Table 1: overall mean 38.9 years (SD 7.95); inclusion range 18-65 years. Not used in the PK/PD model.",
      source_name        = "Mean age (yr) (SD)"
    ),
    SEXF = list(
      description        = "Female sex indicator (0 = male, 1 = female).",
      units              = "(binary)",
      type               = "binary",
      reference_category = "0 (male)",
      notes              = "Table 1: 7 of 54 (13%) female. Not used in the PK/PD model.",
      source_name        = "Females"
    )
  )

  population <- list(
    species        = "human",
    n_subjects     = 52L,
    n_studies      = 1L,
    age_range      = "18-65 years by protocol; cohort means 33.9-41.0 years, overall mean 38.9 years (SD 7.95)",
    weight_range   = "cohort mean weights 69.50-93.87 kg; overall mean 79.81 kg (SD 17.08)",
    height_range   = "cohort mean heights 171.33-179.14 cm; overall mean 176.71 cm (SD 9.685)",
    sex_female_pct = 13,
    race_ethnicity = c(Caucasian = 55.6, `African-American` = 25.9, Hispanic = 13.0, Other = 3.7, Asian = 1.9),
    disease_state  = "HIV-1 infection, antiretroviral treatment-experienced but off all antiretroviral therapy for at least 6 weeks (range 6 weeks to 3 years), CCR5-antagonist-naive, CCR5-tropic virus by the enhanced-sensitivity Trofile assay, screening plasma HIV-1 RNA at least 5,000 copies/mL and CD4+ count at least 250 cells/mm^3",
    dose_range     = "Cenicriviroc (TBR-652) 25, 50, 75, 100 or 150 mg orally once daily for 10 days as monotherapy, or matching placebo, randomised 4:1 within each dose cohort. The 25, 50, 75 and 150 mg doses were given as multiples of a 25 mg tablet (formulation F1); the 100 mg dose used a single 100 mg tablet of a different formulation (F2).",
    regions        = "10 sites: 9 in the United States (52 of 54 patients) and 1 in Argentina (2 patients, both in the 100 mg cohort)",
    endpoint       = "Change from baseline (day 1 predose) in plasma HIV-1 RNA on day 11, in log10 copies/mL. Assayed with the Cobas assay (LLOQ 400 copies/mL), with ultrasensitive PCR (LLOQ 50 copies/mL) for samples at or below that limit.",
    notes          = paste(
      "54 patients were screened and entered study 652-2-201 and are the population of Table 1; the demographic percentages above are that 54-patient denominator. n_subjects = 52 is the analysis set for THIS model, derived from the day-11 row of Table 3 (p. 2772): 9 + 7 + 8 + 10 + 8 = 42 cenicriviroc-treated patients plus 10 placebo patients, all of whom appear in Figure 3 (placebo at Css = 0).",
      "Two per-patient reassignments the source makes explicitly, both of which move a patient between the counts above: patient 2007 was randomised to the 50 mg cohort but mistakenly received 25 mg and was analysed with the 25 mg cohort (n = 9 at 25 mg, n = 7 at 50 mg); patient 5002, in the 150 mg cohort, was retrospectively found to harbour predominantly CXCR4-tropic virus at baseline, was therefore ineligible, and was omitted from the antiviral efficacy analyses (n = 8 at 150 mg here versus n = 9 in the PK Table 2).",
      "Observed medians of the day-11 change from baseline, for comparison against the model, were +0.1, -0.5, -1.3, -1.6, -1.2 and -1.5 log10 copies/mL for placebo and the 25, 50, 75, 100 and 150 mg cohorts (Table 3). Median NADIR changes were -0.7, -1.6, -1.8, -1.4 and -1.7 log10 copies/mL across the five active cohorts; the model targets the day-11 change, not the nadir.",
      "The authors attribute the 100 mg cohort's slightly weaker antiviral effect to its distinct F2 tablet formulation (Discussion, p. 2773). Formulation is not a covariate in this model."
    )
  )

  ini({
    # =========================================================================
    # Simple Emax exposure-response model. Marier 2011 Methods
    # 'Pharmacokinetic/pharmacodynamic modeling' (p. 2770) describes testing
    # "the maximum inhibitory effect model (Emax), with and without sigmoidal
    # factor (gamma), as well as linear models, where viral inhibition was
    # driven by the observed exposure of TBR-652 (i.e., AUC0-24, Cmax, and
    # Css)"; Results (p. 2772) records the outcome of that selection: "A
    # simple Emax model was used to describe the relationship between PK and
    # PD of TBR-652 based on the minimization of the AIC."
    #
    # So the retained form is hyperbolic (gamma = 1, not estimated), driven
    # by Css, with NO baseline / placebo intercept:
    #
    #   dviralLoad = emax * Css / (ic50 + Css)
    #
    # Three independent confirmations that there is no intercept term:
    #   (1) Figure 3's fitted curve passes through the origin, where the
    #       placebo subjects (open circles, Css = 0) are plotted.
    #   (2) The paper's own published percentages-of-Emax (see the note on
    #       ic50 below) are reproduced exactly by this form and by no form
    #       carrying an intercept.
    #   (3) The observed placebo median change was +0.1 log10 copies/mL,
    #       i.e. no placebo effect to model.
    # =========================================================================

    emax <- -1.43
    label("Maximum change from baseline in day-11 log10 HIV-1 RNA at saturating cenicriviroc exposure (log10 copies/mL)")
    # Marier 2011 Results p. 2772: "The Emax and IC50 of TBR-652 were -1.43
    # log10 copies/ml and 13.1 ng/ml, respectively", restated in the
    # Discussion p. 2773 and in the Abstract. SE = 0.138 log10 copies/mL
    # (Results p. 2772), i.e. RSE 9.7% and a Wald 95% CI of
    # (-1.70, -1.16) log10 copies/mL -- a well-determined parameter, as it
    # should be given four of the five cohorts sit on the plateau.
    #
    # Encoded on the LINEAR scale, not as log(emax): the value is NEGATIVE
    # (a reduction in viral load), so it has no logarithm. Same encoding as
    # Nguyen_2025_valbenazine_tmc.R (emax <- -14.2) and
    # Boucher_2018_naproxen_mbma.R (emax <- -1.16).
    #
    # Sign check against a PDF-extraction hazard: the minus sign survives in
    # the raw PDF text layer as a Symbol-font glyph on all three occurrences,
    # and the direction is independently fixed by Figure 3, whose y-axis runs
    # from +1.0 down to -2.5 with the fitted curve asymptoting near -1.45.

    lic50 <- log(13.1)
    label("Log of the average steady-state cenicriviroc concentration producing half of Emax (ng/mL)")
    # Marier 2011 Results p. 2772 and Discussion p. 2773: IC50 = 13.1 ng/mL,
    # described in the Discussion as "The steady-state plasma concentration of
    # TBR-652 associated with 50% of the Emax (IC50)". SE = 6.53 ng/mL
    # (Results p. 2772), i.e. RSE 49.8% and a Wald 95% CI of
    # (0.30, 25.9) ng/mL. That interval is positive but only barely, and the
    # imprecision is structural rather than a transcription problem: only the
    # 25 mg cohort (mean Css 15.92 ng/mL) sits anywhere near the IC50, so the
    # data constrain the plateau far better than the potency. Flagged in the
    # vignette's Assumptions and deviations.
    #
    # SELF-VALIDATING CHECK on this value and on the model form together.
    # Results p. 2772 prints the fraction of Emax expected at each cohort's
    # mean Css: "54.5%, 79.6%, 85.7%, 89.3%, and 95.8%" for 25, 50, 75, 100
    # and 150 mg QD. Evaluating Css / (13.1 + Css) at the Table 2 mean Css
    # values gives 54.9%, 79.8%, 85.9%, 89.4% and 95.9% -- every cohort within
    # 0.4 percentage points, the residue being that the paper averaged the
    # per-subject percentages rather than evaluating at the mean Css. Nothing
    # but this IC50, this driver (Css, not AUC0-24 or Cmax) and this
    # intercept-free hyperbolic form reproduces that row. The vignette asserts
    # it.

    # =========================================================================
    # No inter-individual variability and no residual error are reported.
    # Marier 2011 fitted this curve in Phoenix WinNonlin 6.1 to the pooled
    # individual (Css, delta-log HIV-1 RNA) pairs and reports only the two
    # point estimates and their standard errors -- no omega, no sigma, no
    # residual SD, and no goodness-of-fit statistic beyond the AIC used for
    # model selection. Figure 3 makes the residual scatter plainly visible
    # (roughly +/- 0.5 log10 copies/mL about the curve), but the source
    # publishes no estimate of it, so nothing is invented here. Per the
    # standing policy on unreported residual error, addSd is FIXED at 0 and
    # the model returns the deterministic curve.
    # =========================================================================
    addSd <- fixed(0)
    label("Additive residual error on the day-11 change from baseline in log10 HIV-1 RNA (ZERO - not reported in source)")
  })

  model({
    ic50 <- exp(lic50)

    # -------------------------------------------------------------------------
    # Marier 2011 simple Emax model, Methods p. 2770 / Results p. 2772,
    # drawn as Figure 3 (p. 2773):
    #
    #   dviralLoad = emax * Css / (ic50 + Css)
    #
    # emax is negative, so the returned change from baseline is negative
    # (viral load falls) and bounded below by emax. At CSS_CVC = ic50 the
    # model returns emax / 2 = -0.715 log10 copies/mL, which is the
    # definition of the reported IC50 and is asserted in the vignette. At
    # CSS_CVC = 0 (placebo) it returns exactly 0.
    #
    # Units: CSS_CVC and ic50 are both ng/mL, so the quotient is
    # dimensionless and the product carries emax's units of
    # log10 copies/mL. dviralLoad is a CHANGE FROM BASELINE, so it is
    # added to a subject's baseline log10 HIV-1 RNA to obtain the day-11
    # level; the model does not carry the baseline itself.
    # -------------------------------------------------------------------------
    dviralLoad <- emax * CSS_CVC / (ic50 + CSS_CVC)

    dviralLoad ~ add(addSd)
  })
}
