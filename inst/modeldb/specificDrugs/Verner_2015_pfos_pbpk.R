    "Maisonet M, Marcus M, Kishi R, Miyashita C, Chen MH, Hsieh WS,",
    "Andersen ME, Clewell HJ 3rd, Longnecker MP. (2015). Associations of",
    "Perfluoroalkyl Substances (PFAS) with Lower Birth Weight: An Evaluation",
    "of Potential Confounding by Glomerular Filtration Rate Using a",
    "Physiologically Based Pharmacokinetic Model (PBPK).",
    "Environ Health Perspect 123(12):1317-1324. doi:10.1289/ehp.1408837.",
    "PMCID PMC4671243. Structure, parameter values and gestational lookup",
    "tables from Supplemental Material, 'PBPK Model Code' (acslX listing)",
    "and Figure S1; Monte Carlo distributions from Table 1.",
    "Structural parent model: Loccisano AE, Longnecker MP, Campbell JL Jr,",
    "Andersen ME, Clewell HJ 3rd. (2013) J Toxicol Environ Health A",
    "76(1):25-57."
  )
  vignette <- "Verner_2015_pfas_birthweight"

  units <- list(
    time = "h",
    dosing = "mg",
    concentration = "mg/L",
    amount = "mg",
    weight = "kg"
  )

  paper_specific_compartments <- c(
