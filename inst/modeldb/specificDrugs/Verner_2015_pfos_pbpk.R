    kurine_per_kg    <- fixed(0.005)       ; label("Urinary elimination rate constant (1/h per kg^-0.25)")  # acslX kurinec = 0.005

    # --- Chemical-specific: placental and amniotic-fluid transfer -------
    ktrans1_per_kg   <- fixed(0.46) ; label("Placenta-to-fetal-plasma transfer constant (L/h/kg^0.75)")     # acslX PFOS_k1c = 0.46
    ktrans2_per_kg   <- fixed(1.01) ; label("Fetal-plasma-to-placenta transfer constant (L/h/kg^0.75)")     # acslX PFOS_k2c = 1.01
    ktrans3_per_kg   <- fixed(0.006) ; label("Fetal-body-to-amniotic-fluid transfer constant (L/h/kg^0.75)") # acslX ktrans3c = PFOS*0.006
    ktrans4_per_kg   <- fixed(0.001) ; label("Amniotic-fluid-to-fetal-body transfer constant (L/h/kg^0.75)") # acslX ktrans4c = PFOS*0.001

    # --- Exposure -------------------------------------------------------
    # The pre-pregnancy plasma level is the single exposure knob. The
    # listing's default is 0.013 mg/L; the value carried here is the
    # Monte Carlo mean of Table 1 (13.02 ng/mL). Override per scenario or
    # per simulated subject through rxSolve(params = ...).
    cvinit           <- fixed(0.01302) ; label("Pre-pregnancy (steady-state) plasma PFOS concentration (mg/L)")  # Table 1, initial plasma PFOS 13.02 ng/mL; acslX CVINIT default 0.013
    half_life_yr     <- fixed(5.4)     ; label("PFOS elimination half-life (years)")                             # acslX PFOS_HL = 5.4, from Olsen et al. 2007
    dose_interval    <- fixed(1)        ; label("Intake dosing interval (h)")                                       # acslX DOSE_INT = 1
    ln2_recip        <- fixed(1.44)     ; label("Reciprocal of ln(2) as rounded in the acslX listing (unitless)")   # acslX IVHOURLYDOSE = CVINIT*Vol_dist*DOSE_INT/(1.44*HALF_LIFE); Eq. 2 writes ln(2)/half-life

    # --- The Verner 2015 GFR / birth-weight coupling (Eq. 4) ------------
    # Birth weight (kg) = intercept + beta * GFRratio + residual. The
    # residual defaults to 0, giving the typical-value birth weight; the
    # Monte Carlo draws N(0, 0.441) kg truncated to +/- 0.882 kg and passes
