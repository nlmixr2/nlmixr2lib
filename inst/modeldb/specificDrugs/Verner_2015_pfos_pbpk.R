    fv_body_fet      <- fixed(0.92)   ; label("Fraction of fetal weight available as perfused fetal tissue (unitless)")         # acslX VRF = (0.92*VFet) - VPlasF
    fv_plasma_fet    <- fixed(0.0428) ; label("Fetal plasma volume, fraction of fetal weight")            # acslX VPlasFC = 0.0428
    htc_fet          <- fixed(0.5)    ; label("Fetal haematocrit (unitless)")                             # acslX HtcF = 0.5

    # --- Gestational growth curves --------------------------------------
    # Fetal weight (kg): the sum of two Gompertz terms in hours since
    # conception; it reaches 3.50857 kg at t = 6,570 h, which is exactly the
    # reference birth weight the listing divides by in Eq. 5.
    v_fet_a1         <- fixed(3.779)    ; label("Fetal growth curve, amplitude of first Gompertz term (kg)")       # acslX VFet_av, 3.779
    v_fet_b1         <- fixed(16.081)   ; label("Fetal growth curve, displacement of first Gompertz term")         # acslX VFet_av, 16.081
    v_fet_c1         <- fixed(5.67e-4)  ; label("Fetal growth curve, rate of first Gompertz term (1/h)")           # acslX VFet_av, 5.67e-4
    v_fet_a2         <- fixed(3.833)    ; label("Fetal growth curve, amplitude of second Gompertz term (kg)")      # acslX VFet_av, 3.833
    v_fet_b2         <- fixed(140.178)  ; label("Fetal growth curve, displacement of second Gompertz term")        # acslX VFet_av, 140.178
    v_fet_c2         <- fixed(7.01e-4)  ; label("Fetal growth curve, rate of second Gompertz term (1/h)")          # acslX VFet_av, 7.01e-4
    wt_fet_ref       <- fixed(3.50857)  ; label("Reference fetal weight at delivery (kg)")                         # acslX Birthweight = 3.50857 and VFet = (Birthweight/3.50857)*VFet_av
    v_pla_a          <- fixed(0.85)     ; label("Placenta growth curve, amplitude (L)")                            # acslX VPla_av, 0.85
    v_pla_b          <- fixed(9.434)    ; label("Placenta growth curve, displacement")                             # acslX VPla_av, 9.434
    v_pla_c          <- fixed(5.23e-4)  ; label("Placenta growth curve, rate (1/h)")                               # acslX VPla_av, 5.23e-4
    v_mam_a          <- fixed(0.0065)   ; label("Mammary growth curve, amplitude (fraction of pre-pregnancy body weight)")  # acslX VMam, 0.0065
    v_mam_b          <- fixed(7.444868477) ; label("Mammary growth curve, displacement")                           # acslX VMam, 7.444868477
    v_mam_c          <- fixed(0.000678) ; label("Mammary growth curve, rate (1/h)")                                # acslX VMam, 0.000678
    v_fat_a          <- fixed(0.09)     ; label("Fat growth curve, amplitude (fraction of pre-pregnancy body weight)")      # acslX VFat, 0.09
    v_fat_b          <- fixed(12.90995862) ; label("Fat growth curve, displacement")                               # acslX VFat, 12.90995862
    v_fat_c          <- fixed(0.000797) ; label("Fat growth curve, rate (1/h)")                                    # acslX VFat, 0.000797

    # --- Chemical-specific: tissue:plasma partition coefficients --------
    # acslX block 'Tissue:plasma partition coefficients (from rat)'.
    lkp_liver         <- fixed(log(3.72))   ; label("Liver:plasma partition coefficient (unitless)")         # acslX PFOS_PL = 3.72; Table 1 Monte Carlo mean 3.72, SD 0.558
    lkp_fat           <- fixed(log(0.14))     ; label("Fat:plasma partition coefficient (unitless)")           # acslX PFOS_PFat = 0.14
    lkp_kidney        <- fixed(log(0.80))  ; label("Kidney:plasma partition coefficient (unitless)")        # acslX PFOS_PK = 0.80
    lkp_skin          <- fixed(log(0.29))    ; label("Skin:plasma partition coefficient (unitless)")          # acslX PFOS_PSk = 0.29
    lkp_rest          <- fixed(log(0.20))    ; label("Rest-of-body:plasma partition coefficient (unitless)")  # acslX PFOS_PR = 0.20; Table 1 Monte Carlo mean 0.20, SD 0.030
    lkp_gut           <- fixed(log(0.57))     ; label("Gut:plasma partition coefficient (unitless)")           # acslX PFOS_PG = 0.57
    lkp_mammary       <- fixed(log(0.16)) ; label("Mammary:plasma partition coefficient (unitless)")       # acslX PFOS_PMam = 0.16
    lkp_placenta      <- fixed(log(0.41)); label("Placenta:plasma partition coefficient (unitless)")      # acslX PFOS_PPla = 0.41
    lkp_rest_fet      <- fixed(log(0.20)); label("Rest-of-fetal-body:plasma partition coefficient (unitless)")  # acslX PFOS_PRF = 0.20

    # --- Chemical-specific: plasma protein binding ----------------------
    fu               <- fixed(0.025)     ; label("Free fraction in maternal plasma (unitless)")  # acslX PFOS_Free = 0.025; Table 1 Monte Carlo mean 0.025, SD 0.004
    fu_fet           <- fixed(0.025) ; label("Free fraction in fetal plasma (unitless)")     # acslX PFOS_FreeF = 0.025; Table 1 Monte Carlo mean 0.025, SD 0.004

    # --- Chemical-specific: renal reabsorption and urinary excretion ----
    tm_per_kg        <- fixed(3.5) ; label("Maximum renal reabsorption velocity (mg/h/kg^0.75)")  # acslX PFOS_TMC = 3.5; Table 1 Monte Carlo mean 3.5, SD 0.525
