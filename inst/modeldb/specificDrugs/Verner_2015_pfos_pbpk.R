  population <- list(
    species = "human",
    n_subjects = 0L,
    n_studies = 0L,
    age_range = "reproductive age (not otherwise specified)",
    weight_range = paste(
      "Pre-pregnancy 37.0-134.0 kg, mean 70.3 (SD 14.3), from the Norwegian",
      "Mother and Child Cohort Study (Table 1). The acslX listing default is",
