    q_kidney_ref <- q_kidney_ref + (57.12 - 51.36) * min(1, max(0, (wk - 11) / (12 - 11)))
    q_kidney_ref <- q_kidney_ref + (46.32 - 57.12) * min(1, max(0, (wk - 12) / (13 - 12)))
    q_kidney_ref <- q_kidney_ref + (44.73 - 46.32) * min(1, max(0, (wk - 13) / (15 - 13)))
    q_kidney_ref <- q_kidney_ref + (45.36 - 44.73) * min(1, max(0, (wk - 15) / (17 - 15)))
    q_kidney_ref <- q_kidney_ref + (41.8 - 45.36) * min(1, max(0, (wk - 17) / (18 - 17)))
    q_kidney_ref <- q_kidney_ref + (46.53 - 41.8) * min(1, max(0, (wk - 18) / (19 - 18)))
    q_kidney_ref <- q_kidney_ref + (46.08 - 46.53) * min(1, max(0, (wk - 19) / (22 - 19)))
    q_kidney_ref <- q_kidney_ref + (47.85 - 46.08) * min(1, max(0, (wk - 22) / (23 - 22)))
    q_kidney_ref <- q_kidney_ref + (43.05 - 47.85) * min(1, max(0, (wk - 23) / (24 - 23)))
    q_kidney_ref <- q_kidney_ref + (41.16 - 43.05) * min(1, max(0, (wk - 24) / (25 - 24)))
    q_kidney_ref <- q_kidney_ref + (47.52 - 41.16) * min(1, max(0, (wk - 25) / (26 - 25)))
    q_kidney_ref <- q_kidney_ref + (43.41 - 47.52) * min(1, max(0, (wk - 26) / (27 - 26)))
    q_kidney_ref <- q_kidney_ref + (48.57 - 43.41) * min(1, max(0, (wk - 27) / (28 - 27)))
    q_kidney_ref <- q_kidney_ref + (46.36 - 48.57) * min(1, max(0, (wk - 28) / (29 - 28)))
    q_kidney_ref <- q_kidney_ref + (36.68 - 46.36) * min(1, max(0, (wk - 29) / (31 - 29)))
    q_kidney_ref <- q_kidney_ref + (39.44 - 36.68) * min(1, max(0, (wk - 31) / (32 - 31)))
    q_kidney_ref <- q_kidney_ref + (46.46 - 39.44) * min(1, max(0, (wk - 32) / (33 - 32)))
    q_kidney_ref <- q_kidney_ref + (44.13 - 46.46) * min(1, max(0, (wk - 33) / (34 - 33)))
    q_kidney_ref <- q_kidney_ref + (26.7 - 44.13) * min(1, max(0, (wk - 34) / (36 - 34)))
    q_kidney_ref <- q_kidney_ref + (33.92 - 26.7) * min(1, max(0, (wk - 36) / (37 - 36)))
    q_kidney_ref <- q_kidney_ref + (35.46 - 33.92) * min(1, max(0, (wk - 37) / (38 - 37)))
