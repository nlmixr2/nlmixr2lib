Verner_2015_pfos_pbpk <- function() {
  description <- paste(
    "PBPK (whole-body, gestational; original implementation in acslX).",
    "perfluorooctane sulfonate (PFOS) in pregnant women, from the Verner et al. 2015 modification of",
    "the Loccisano et al. 2013 human gestation PBPK model. Fifteen",
    "mass-balance states: maternal plasma, liver, gut, fat, mammary tissue,",
    "skin, kidney, rest of body, a glomerular filtrate compartment feeding a",
    "urinary storage compartment through saturable renal reabsorption, the",
    "placenta, and a separate fetal circulation (fetal plasma, rest of fetal",
    "body, amniotic fluid) reached only by bidirectional placental diffusion.",
    "Model time is HOURS SINCE CONCEPTION, so gestational week wk = time/168",
    "drives the maternal renal plasma flow, glomerular filtration rate,",
    "plasma volume, haematocrit and amniotic-fluid volume lookup tables and",
    "the fetal, placental, fat and mammary growth curves. Exposure is a",
    "constant hourly intake back-calculated from a pre-pregnancy plasma level",
    "assumed to be at steady state, so there are no dose records. The",
    "Verner 2015 modification is the GFR-birth-weight coupling: the covariate",
    "RENALFUNC_REL (the paper's GFRratio) simultaneously scales the whole",
    "gestational GFR profile and sets birth weight through a meta-analytic",
    "regression, and birth weight in turn rescales the fetal growth curve, so",
    "a single subject-level renal-function draw induces the confounded",
    "association between plasma PFAS and birth weight that the paper",
    "quantifies. Deterministic typical-value model (no IIV, no residual",
    "error): population variability was generated by Monte Carlo sampling of",
    "the parameters in Table 1, not by estimated random effects."
  )
  reference <- paste(
