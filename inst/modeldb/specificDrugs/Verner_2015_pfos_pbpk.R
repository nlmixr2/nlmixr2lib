    # acslX BALANCE_DOSE: (cumulative intake + initial body burden) minus
    # everything currently in the system. Should hold at zero to solver
    # tolerance for the whole pregnancy.
    a_initial <- cvinit * (v_plasma_0 * fu + kp_gut * v_gut + kp_liver * v_liver +
                           kp_fat * v_fat_0 + kp_kidney * v_kidney +
                           kp_rest * v_rest + kp_mammary * v_mammary_0 +
                           kp_skin * v_skin)
    MassBalance <- (a_intake + a_initial) -
                   (plasma + gut + liver + fat + kidney + rest + mammary + skin +
                    placenta + plasma_fet + filtrate + storage + urine +
                    rest_fet + amniotic)
  })
