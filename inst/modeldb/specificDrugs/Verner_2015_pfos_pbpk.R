    bw_resid         <- fixed(0)      ; label("Birth-weight regression residual for this subject (kg)")        # Table 1, residual birth weight 0 +/- 441 g, bounds -882 to 882 g

    # =====================================================================
    # No IIV and no residual error. Verner et al. ran a deterministic PBPK
    # model 250,000 times under the Table 1 input distributions; they did
    # not estimate random effects and report no residual-error model.
    # =====================================================================
  })

  model({
    # =====================================================================
    # 1. Time base. Model time is HOURS SINCE CONCEPTION.
    # =====================================================================
    gd <- time / 24    # gestation day   (acslX GD = T/24)
    wk <- gd / 7       # gestation week  (acslX WK = GD/7)

    # Partition coefficients are carried on the log scale in ini() (package
    # convention; cf. Zhang_2024_f53b_human_pbpk.R) and back-transformed here.
    kp_fat      <- exp(lkp_fat)
    kp_gut      <- exp(lkp_gut)
    kp_kidney   <- exp(lkp_kidney)
    kp_liver    <- exp(lkp_liver)
    kp_mammary  <- exp(lkp_mammary)
    kp_placenta <- exp(lkp_placenta)
    kp_rest     <- exp(lkp_rest)
    kp_rest_fet <- exp(lkp_rest_fet)
    kp_skin     <- exp(lkp_skin)

    # =====================================================================
    # 2. Gestational physiology lookup tables.
    #
    # The acslX listing supplies five TABLE() functions of gestational week
    # and interpolates them linearly, holding the end values outside the
    # tabulated range. Each is written here in hinge form,
    #     f  <- y[1]
    #     f  <- f + (y[k+1] - y[k]) * min(1, max(0, (wk - x[k])/(x[k+1] - x[k])))
    # which is algebraically identical to linear interpolation with clamped
    # ends (verified against stats::approx(..., rule = 2) to machine zero
    # over wk in [-2, 45]) and keeps every tabulated knot visible on the
    # line that uses it. Units: q_kidney_ref and gfr_ref L/h, fv_plasma a
    # fraction of body weight, htc unitless, v_amniotic L.
    # =====================================================================
    # q_kidney_ref
