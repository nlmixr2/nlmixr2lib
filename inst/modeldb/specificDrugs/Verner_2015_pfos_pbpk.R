  covariateData <- list(
    WT = list(
      description = "Body weight",
      units = "kg",
      type = "continuous",
      reference_category = NULL,
      notes = paste(
        "Maternal PRE-PREGNANCY body weight (acslX constant BWINIT). The",
        "acslX listing carries BWINIT = 60.9 kg, the Loccisano et al. 2013",
        "reference pregnant woman; the Monte Carlo analysis resamples it.",
        "Every maternal tissue volume except skin is a fixed fraction of",
        "this pre-pregnancy weight, the initial cardiac output and the",
        "urinary rate constant are allometric in it, and the time-varying",
        "gestational body weight BW = WT + fat + mammary + placental +",
        "fetal + amniotic increments (which drives the saturable",
        "reabsorption Tm) is built up from it. Table 1 gives the Monte",
        "Carlo distribution as 70.3 +/- 14.3 kg (range 37.0-134.0) from",
