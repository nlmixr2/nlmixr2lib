Deshpande_2025_tigecycline <- function() {
  description <- paste(
    "Monte Carlo simulation PK model for inhaled and intravenous tigecycline in virtual",
    "adults with Mycobacterium avium-complex lung disease (Deshpande 2025). Two",
    "compartments: an inhaled dose enters the epithelial lining fluid (ELF), which loses",
    "drug with a total ELF clearance of 0.0068 L/h from a 0.0007 L volume, of which the",
    "first-order lung-to-systemic transfer (Ka = 1.002 1/h) carries about 10% into the",
    "systemic circulation; the remainder leaves the lung by non-systemic routes. An IV dose",
    "enters the systemic compartment (CL 23.1 L/h, V 315 L), which has no return path to",
    "the ELF. Log-normal IIV of 25% CV on all five parameters, no residual error",
    "(simulation-only model, ADAPT 5 PRIOR)."
  )
  reference <- paste(
    "Deshpande D, Srivastava S, Gumbo T.",
    "Tigecycline pharmacodynamics in the hollow fiber system of Mycobacterium",
    "avium-complex lung disease and the utility of MICs and time-kill studies in drug",
    "development.",
    "Front Pharmacol. 2025;16:1682477.",
    "doi:10.3389/fphar.2025.1682477. PMID 41311832. PMCID PMC12647067."
  )
  vignette <- "Deshpande_2025_tigecycline"
  # Declared explicitly because the registry's automatic detection only
  # recognises `depot` and `central`: an inhaled dose targets cmt = "elf" and an
  # intravenous dose cmt = "central" (Methods, 'Monte Carlo experiments').
  dosing <- c("elf", "central")
  units <- list(time = "h", dosing = "mg", concentration = "mg/L")

  compartmentData <- list(
    elf = list(analyte = "tigecycline", units = "mg", specimen = "epithelial lining fluid", verified = TRUE),
    central = list(analyte = "tigecycline", units = "mg", specimen = "plasma", verified = TRUE)
  )

  covariateData <- list()

  population <- list(
    species = "human",
    n_subjects = 10000L,
    age_range = "not reported (virtual adults)",
    weight_range = "not reported (no covariates in the model)",
    race_ethnicity = "not reported",
    disease_state = paste(
      "Virtual patients with Mycobacterium avium-complex (MAC) lung disease; the model",
      "is a simulation (Monte Carlo experiment) model, not fitted to patient data."
    ),
    dose_range = paste(
      "Inhaled and intravenous tigecycline 0, 1, 10, 20, 30, 40, 50, 100 and 200 mg once",
      "daily (Methods)."
    ),
    regions = "not applicable (in silico)",
    notes = paste(
      "Inhaled-route parameters were derived by the authors from the human ELF and",
      "systemic PK generated by the Himstedt 2022 semi-mechanistic PBPK model, assuming",
      "no gastrointestinal absorption of the inhaled dose; IV dosing was based on",
      "Gotfried 2017. IIV was set to 25% CV on every parameter (Methods: Himstedt rat",
      "4.5% / 5.36%, Gotfried human 17.75% / 21.26% for CL / V). 10,000 virtual subjects",
      "per dose in ADAPT 5 (Table 5)."
    )
  )

  ini({
    # Inhaled-route ELF parameters -- Deshpande 2025 Table 5, 'Parameters in the
    # domain of input'. The ELF clearance is the TOTAL loss from the ELF; the
    # lung-to-systemic transfer constant is the systemic share of it (see the
    # vignette for the reconciliation against the Table 5 lung AUC0-24 values).
    lcl_elf_total <- log(0.0068); label("Total ELF clearance (L/h)") # Table 5: ELF clearance in L/h = 0.68 x 10-2
    lv_elf <- log(0.0007); label("ELF volume (L)") # Table 5: ELF volume in L = 0.07 x 10-2
    lk_elf_central <- log(1.002); label("First-order lung-to-systemic transfer rate constant Ka (1/h)") # Table 5: Ka (from lung to systemic) = 1.002 (unit not printed; per hour assumed)

    # Systemic parameters -- Table 5.
    lcl <- log(23.1); label("Systemic clearance (L/h)") # Table 5: Systemic clearance L/h = 23.1
    lvc <- log(315); label("Systemic volume (L)") # Table 5: Systemic volume in L = 315

    # IIV -- Table 5 IIV (%) = 25.0 for every parameter; Methods: 'we set these at
    # 25% in our MCE'. omega^2 = log(1 + 0.25^2) = 0.0606246. The ADAPT PRIOR
    # covariance matrix is not reported, so the etas are uncorrelated.
    etalcl_elf_total ~ 0.0606246 # Table 5: ELF clearance IIV 25.0 %
    etalv_elf ~ 0.0606246 # Table 5: ELF volume IIV 25.0 %
    etalk_elf_central ~ 0.0606246 # Table 5: Ka IIV 25.0 %
    etalcl ~ 0.0606246 # Table 5: Systemic clearance IIV 25.0 %
    etalvc ~ 0.0606246 # Table 5: Systemic volume IIV 25.0 %

    # Residual error -- not reported; the source performs simulation only.
    propSd <- fixed(0); label("Proportional residual error, plasma (fraction; ZERO - not reported in source)") # not reported: simulation-only model
    propSd_Celf <- fixed(0); label("Proportional residual error, ELF (fraction; ZERO - not reported in source)") # not reported: simulation-only model
  })
  model({
    cl_elf_total <- exp(lcl_elf_total + etalcl_elf_total)
    v_elf <- exp(lv_elf + etalv_elf)
    k_elf_central <- exp(lk_elf_central + etalk_elf_central)
    cl <- exp(lcl + etalcl)
    vc <- exp(lvc + etalvc)

    # Total first-order loss from the ELF; k_elf_central * v_elf of the total
    # ELF clearance goes to the systemic circulation, and the remainder
    # (cl_elf) leaves the lung by non-systemic routes.
    kel_elf_total <- cl_elf_total / v_elf
    cl_elf <- cl_elf_total - k_elf_central * v_elf
    kel <- cl / vc

    d/dt(elf) <- -kel_elf_total * elf
    d/dt(central) <- k_elf_central * elf - kel * central

    Cc <- central / vc
    Celf <- elf / v_elf
    Cc ~ prop(propSd)
    Celf ~ prop(propSd_Celf)
  })
}
