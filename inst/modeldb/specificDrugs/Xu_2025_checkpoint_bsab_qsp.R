      "0.1-5 mg/kg and anti-4-1BB/PD-L1 3.25-26 mg/kg, each also compared as",
      "half-dose twice weekly versus full-dose once weekly.",
      sep = " "
    ),
    notes = paste(
      "Not a fitted population model. Initial tumour microenvironment composition",
      "was set from literature knowledge at 1e5 tumour cells, 370 T cells and 10",
      "APCs per 1 mm3 of tumour. A virtual mouse population is 100 parameter sets",
      "sampled within physiological ranges (initial tumour volume, tumour growth",
      "and death rates, checkpoint expression levels and initial cell counts).",
      "The global sensitivity analysis assumed a 100 mm3 starting tumour and used",
      "day-25 tumour volume as the output. Implemented in MATLAB SimBiology and",
      "solved with ode15s; parameters were estimated globally with patternsearch.",
      sep = " "
    )
  )

