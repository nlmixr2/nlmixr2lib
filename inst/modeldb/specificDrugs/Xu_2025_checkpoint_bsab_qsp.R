    promoter_2_a = list(analyte = "active NF-kB-driven promoter", units = "dimensionless", specimen = "not applicable", verified = TRUE),
    # ---- checkpoint-recruited second messengers ----
    inhibitor_1  = list(analyte = "PD-1/PD-L1-recruited inhibitor (SHP2)", units = "nmol/L", specimen = "not applicable", verified = TRUE),
    inhibitor_2  = list(analyte = "CTLA4/CD80-CD86-recruited inhibitor", units = "nmol/L", specimen = "not applicable", verified = TRUE),
    inhibitor_3  = list(analyte = "TIGIT/CD155-recruited inhibitor", units = "nmol/L", specimen = "not applicable", verified = TRUE),
    inhibitor_n  = list(analyte = "SHP099-inactivated inhibitor_1", units = "nmol/L", specimen = "not applicable", verified = TRUE),
