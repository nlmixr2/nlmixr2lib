    # ================================================================
    # Compartment capacities -- Supplementary Table S1, "Compartments"
    # ================================================================
    Vc <- fixed(7e-4); label("Central compartment volume for antibody drugs in mice [L]")  # Table S1 Compartments: central = 6.9999999999999999E-4 liter (doi:10.1208/s12248-019-0332-z)
