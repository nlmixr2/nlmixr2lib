Xu_2025_checkpoint_bsab_qsp <- function() {
  description <- paste(
    "QSP. Preclinical (mouse). Multi-scale mechanistic quantitative systems",
    "pharmacology platform for checkpoint-targeting immuno-modulatory bispecific",
    "antibodies in syngeneic tumour-bearing mice. Couples a TCR/CD3-driven T cell",
    "intracellular signalling network (ZAP70, PI3K, AKT, ERK, NF-kB, IL-2, IFN-gamma",
    "and two transcriptional promoters) to mass-action binding of eleven immune",
    "checkpoints across T cells, tumour cells and antigen-presenting cells",
    "(PD-1/PD-L1, CTLA4/CD80-CD86, CD28/CD80-CD86, TIGIT/CD155, LAG3, 4-1BB/4-1BBL,",
    "OX40/OX40L and MHC/TCR), logistic tumour and T cell growth, and a three-stage",
    "dead-cell clearance chain that determines measured tumour volume. Two",
    "bispecific antibodies are parameterised end to end - anti-TIGIT/PD-L1 (drug_3)",
    "and anti-4-1BB/PD-L1 (drug_11) - each with its own two-compartment mouse",
    "plasma PK, an intraperitoneal depot, a tumour partition coefficient and the",
    "full drug-checkpoint dimer and trimer cascade on both tumour and APC surfaces.",
    "A SHP2-inhibitor (SHP099) module is carried structurally but is not dosed by",
    "default because its published PK constants are not reproducible (see the",
    "vignette Errata). 59 ODE states and 122 parameters, translated from the",
    "SimBiology model in Supplementary Table S1. Deterministic mechanism model:",
