  ini({
    # ==================================================================
    # PHARMACOKINETIC LAYER -- Kastrissios 2006 Table IV, "Final
    # Pharmacokinetic Parameter Estimates" (a FOCE fit in NONMEM v5).
    # Rohatagi 2008 does not re-estimate the PK; its Methods state that
    # the concentrations driving equation 7 "were the individual (post
    # hoc) estimates from population PK and PK/PD models developed
    # previously" and summarise that model in prose. Every value below
    # is transcribed from Kastrissios 2006 Table IV, which Rohatagi
    # 2008 cites as its reference 1, and each is cross-checked against
    # the summary Rohatagi 2008 prints in its own Methods. Nothing in
    # Kastrissios 2006 Table IV is flagged FIX -- every row carries a
    # CV% and a 95% confidence interval -- so no PK parameter is
    # wrapped in fixed(). The one genuinely fixed quantity there is
    # absolute oral bioavailability F, which "was not uniquely
    # estimable and therefore was assumed to be equal to the product of
    # 1 and Frel"; that unit constant appears in model() as the
    # implicit multiplier of frel, not as an ini() entry, so every
    # clearance and volume below is APPARENT.
    # ==================================================================
    lvc <- log(166)
    label("Apparent central volume Vc/F at the 73.3 kg reference weight (L)")
    # Kastrissios 2006 Table IV: Vc/F = 166 L, CV 8%, 95% CI (141, 191).
    # Rohatagi 2008 Methods: "The typical apparent volume of the central
    # compartment (Vc/F) in a 73-kg subject was 166 l".

    lvp <- log(483)
    label("Apparent peripheral volume Vp/F (L)")
    # Kastrissios 2006 Table IV: Vp/F = 483 L, CV 7%, 95% CI (417, 549).
    # Not restated by Rohatagi 2008, which describes only "an open
    # two-compartment model with first-order absorption".

    lq <- log(75)
    label("Apparent inter-compartmental clearance Q/F (L/h)")
    # Kastrissios 2006 Table IV: Q/F = 75 L/h, CV 7%, 95% CI (64, 86).

    lcl <- log(34.1)
    label("Apparent oral clearance CL/F, 2-200 mg doses, female reference subject (L/h)")
    # Kastrissios 2006 Table IV row "CL/F, L/h, extensive metabolizer
    # phenotype / 2- to 200-mg doses" = 34.1 L/h, CV 6%, 95% CI (29.8,
    # 38.4). This is the FEMALE value: equation 7's Gender indicator is
    # 1 for MALE, so the male typical value is 34.1 * exp(0.325) = 47.2
    # L/h, which is exactly the number Rohatagi 2008 Methods quotes
    # ("Apparent oral clearance (CL/F) was 47.2 l h-1 in the dose range
    # 2-200 mg"). See the SEXF covariateData notes.

    lcl_highdose <- log(19.5)
    label("Apparent oral clearance CL/F, 400-800 mg doses, female reference subject (L/h)")
    # Kastrissios 2006 Table IV row "CL/F ... / 400- to 800-mg doses" =
    # 19.5 L/h, CV 17%, 95% CI (12.9, 26.1). Selected inside model() by
    # DOSE_HIGH = 1. 1 - 19.5/34.1 = 42.8%, Rohatagi 2008's "reduced by
    # 43% at higher doses (>200 mg)". Never active in the dental-pain
    # cohort, whose doses are 10 to 200 mg.

    lka <- log(0.542)
    label("First-order absorption rate constant KA (1/h)")
    # Kastrissios 2006 Table IV: KA = 0.542 1/h, CV 5%, 95% CI (0.489,
    # 0.595); log(2)/0.542 = 1.28 h absorption half-life.

    ltlag <- log(0.236)
    label("Absorption lag time TLAG (h)")
    # Kastrissios 2006 Table IV: TLAG = 0.236 h, CV 1%, 95% CI (0.232,
    # 0.240). Rohatagi 2008 Methods: "an absorption lag time (median 14
    # min)"; 0.236 h * 60 = 14.2 min.

    led50 <- log(221)
    label("Dose at which relative bioavailability is half maximal, D50 (mg)")
    # Kastrissios 2006 Table IV row "D50 for F, mg" = 221 mg, CV 14%,
    # 95% CI (161, 281). Rohatagi 2008 Methods: bioavailability
    # "decreased with increasing doses according to a saturation model,
    # reaching 50% reduction at a dose of 221 mg"; 221/(221 + 221) =
    # 0.500 exactly.

    e_evening_fdepot <- 0.351
    label("Log-scale increase in relative bioavailability for an evening dose (unitless)")
    # Kastrissios 2006 Table IV row "KFrel-PM Dose" = 0.351, CV 13%,
    # 95% CI (0.261, 0.441). exp(0.351) - 1 = 42.0%, Rohatagi 2008's
    # "Oral bioavailability was 42% greater following night-time
    # relative to day-time doses".

    e_sexf_cl <- 0.325
    label("Log-scale effect of MALE sex on apparent oral clearance (unitless)")
    # Kastrissios 2006 Table IV row "KCL/F-SEX" = 0.325, CV 24%, 95% CI
    # (0.171, 0.479). Applied in model() to (1 - SEXF) because the
    # source indicator is 1 for male. exp(0.325) = 1.384.

    e_cyp2d6_pmim_cl <- -1.01
    label("Log-scale effect of pooled poor/intermediate CYP2D6 phenotype on CL/F (unitless)")
    # Kastrissios 2006 Table IV row "KCL/F-CYP2D6 (poor and intermediate
    # metabolizer)" = -1.01, CV 16%, 95% CI (-1.33, -0.69).
    # 1 - exp(-1.01) = 63.6%, Rohatagi 2008's "reduced ... by 64% in
    # subjects expressing poor and intermediate ... CYP 2D6 phenotypes".

