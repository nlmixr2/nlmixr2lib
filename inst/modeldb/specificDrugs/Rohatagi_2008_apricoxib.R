    # intercepts incrementally, beta_1 = theta_1, beta_2 = beta_1 +
    # theta_2, beta_3 = beta_2 + theta_3, beta_4 = beta_3 + theta_4,
    # "because, with the exception of theta_1, theta estimates can be
    # constrained to be negative, keeping the beta-values decreasing
    # with increasing pain score". Nothing in Table 3 is flagged fixed;
    # every row carries a standard error.
    # ==================================================================
    b1_pr <- -3.30
    label("Logit of P(pain relief score >= 1) extrapolated to time 0 (logit units)")
    # Table 3 row "Logit of the probability that PR >= 1 extrapolated to
