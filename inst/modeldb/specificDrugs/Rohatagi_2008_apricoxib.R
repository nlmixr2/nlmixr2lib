    propSd <- sqrt(0.069)
    label("Proportional residual error on the apricoxib plasma concentration (fraction)")
    # Kastrissios 2006 equation 3, y_ij = yhat_ij * (1 + eps_ij), i.e.
    # proportional in linear space; Table IV reports sigma^2 = 0.069, a
    # VARIANCE, CV 6%, 95% CI (0.061, 0.077). sqrt(0.069) = 0.2627,
    # matching that paper's printed 26.3% residual variability.

    # ==================================================================
    # PAIN RELIEF MODEL -- Rohatagi 2008 Table 3. A proportional-odds
    # categorical response model, equation 4:
    #   P(Y_ij >= k | eta_i) =
    #     expit(beta_k + f_p(t_ij) + f_D(C_ij) + eta_i)
