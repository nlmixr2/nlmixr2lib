    # gives the round-trip: "Corresponds to probability of PR >= 1
    # extrapolated to 0 h = 0.04 or 4%"; expit(-3.30) = 0.0355.

    b2b1_pr <- -2.39
    label("Incremental change in logit from PR >= 1 to PR >= 2 (logit units)")
    # Table 3: theta_2 = -2.39, SE 0.11, odds ratio exp(-2.39) = 0.092
