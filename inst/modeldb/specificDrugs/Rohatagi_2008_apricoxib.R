    etalvp   ~ 0.234   # Kastrissios 2006 Table IV: omega^2 Vp/F  = 0.234, CV 15%, 95% CI (0.166, 0.302)
    etalq    ~ 0.229   # Kastrissios 2006 Table IV: omega^2 Q/F   = 0.229, CV 20%, 95% CI (0.140, 0.318)
    etalcl   ~ 0.125   # Kastrissios 2006 Table IV: omega^2 CL/F  = 0.125, CV 16%, 95% CI (0.086, 0.164)
