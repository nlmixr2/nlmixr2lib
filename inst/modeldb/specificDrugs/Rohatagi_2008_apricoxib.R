Rohatagi_2008_apricoxib <- function() {
  description <- paste(
    "Joint pain-relief / rescue-medication / onset-time exposure-response",
    "model for the selective cyclooxygenase-2 (COX-2) inhibitor apricoxib",
    "(development code CS-706) in adults with acute postoperative dental",
    "pain after third-molar extraction. Four coupled sub-models, the terms",
    "of the paper's equations 1 to 3. (1) A proportional-odds categorical",
    "response model for the five-point pain relief (PR) score 0 to 4, whose",
    "shared linear predictor is the sum of a first-order placebo response",
    "Ep * (1 - exp(-Kp * t)), an Emax drug effect Emax * Cp / (Cp + EC50)",
    "on the model-predicted apricoxib plasma concentration, and one",
    "additive subject-level random effect on the logit. (2) A rescue",
    "medication (discontinuation) hazard h = h0 * lambda^PR that declines",
    "five-fold per unit increase in pain relief score; it is integrated",
    "here as a cumulative-hazard state driven by the expectation of",
    "lambda^PR over the categorical score distribution, so the",
    "probability of having required rescue medication by time t is",
    "1 - exp(-cumhaz). (3) A saturable dose-response for the probability",
    "of meaningful pain relief (MPR) in patients who required rescue",
    "medication, mixed with the dose-independent 98.2 percent MPR",
    "probability in patients who did not. (4) Log-normal onset time of",
    "meaningful pain relief (TMPR), reported as an absolute time in",
    "patients who required no rescue medication and as a fraction of the",
    "individual rescue time in patients who did. The apricoxib plasma",
    "concentration driving the Emax term is generated by the two-",
    "compartment first-order-absorption population PK model of",
    "Kastrissios 2006, reproduced in full here so the file is",
    "self-contained; see modellib('Kastrissios_2006_apricoxib')."
  )
