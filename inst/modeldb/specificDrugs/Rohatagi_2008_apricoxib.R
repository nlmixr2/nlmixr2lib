    b4b3_pr <- -3.45
    label("Incremental change in logit from PR >= 3 to PR >= 4 (logit units)")
    # Table 3: theta_4 = -3.45, SE 0.11, odds ratio exp(-3.45) = 0.032
    # against the printed 0.03.

    eplac_pr <- 12.0
    label("Maximum extent of the placebo response on the pain relief logit, Ep (logit units)")
    # Table 3 row "Maximum extent of placebo response", Ep = 12.0, SE
    # 1.2. Equation 6: f_p(t) = Ep * (1 - exp(-Kp * t)).

    lkplac_pr <- log(0.055)
    label("First-order rate constant for stabilization of the placebo response, Kp (1/h)")
    # Table 3 row "Rate of stabilization of placebo response over time
    # (h-1)", Kp = 0.055, SE 0.009 (16% RSE). Held on the log scale here
    # so it stays positive; the paper reports it untransformed. See the
    # vignette Assumptions and deviations section for the prose-versus-
    # table note: the Results and Discussion describe the placebo
    # response as having "stabilized after about 4 h", which is a
    # statement about the raw score bar plots of Figure 3, whereas
    # Kp = 0.055 1/h gives a 12.6 h half-life so that f_p reaches only
    # 20% of Ep by 4 h and 73% by 24 h. The estimate, not the prose, is
    # encoded; the SE rules out a factor-of-ten transcription error
    # (0.55 1/h would imply a 1.6% RSE).

    emax_pr <- 12.6
    label("Maximum extent of the apricoxib response on the pain relief logit, Emax (logit units)")
    # Table 3 row "Maximum extent of CS-706 response", Emax = 12.6, SE
    # 0.6. Equation 7: f_D(Cp) = Emax * Cp / (Cp + EC50).

    lec50_pr <- log(87.0)
    label("Apricoxib plasma concentration producing half the maximum pain relief response, EC50 (ng/mL)")
    # Table 3 row "Plasma concentration producing 50% of maximum
    # response (ng ml-1)", EC50 = 87.0, SE 8.9. Abstract and Discussion:
    # 87 ng/mL is "the median peak plasma concentration achieved after a
    # 50-mg oral dose".

    etab1_pr ~ 9.90
    # Table 3 row "Intersubject variability", omega^2 = 9.90, SE 1.21,
    # printed in the placebo-response group. It is the variance of the
    # single additive subject-level random effect eta_i of equation 4,
    # which shifts the whole linear predictor and is therefore exactly
    # equivalent to intersubject variability on the baseline intercept
    # beta_1 = theta_1 (all four beta_k shift together). Entered as a
    # VARIANCE on the logit scale, not as a CV: equation 4 adds eta_i
    # inside the logit rather than multiplying a typical value, so the
    # log-normal parameterisation of equation 8 does not apply to it.
    # sqrt(9.90) = 3.15 logit units, a large but unremarkable spread for
    # a categorical pain-relief model of this family (the paper's
    # reference 4, Mandema & Stanski 1996, uses the same construction).

    # ==================================================================
    # RESCUE MEDICATION MODEL -- Rohatagi 2008 Table 4. Equation 11 is
    # the hazard h_ij = h0 * lambda^PR_ij, an "exponentially declining
    # function of the last observed pain relief score"; equation 10
    # converts it to the interval probability P_ij = 1 - exp(-h_ij *
    # dT_ij); equation 12 gives T50 = log(2)/h.
    # ==================================================================
    lh0_remd <- log(2.08)
    label("Rescue-medication (discontinuation) hazard at pain relief score 0, h0 (1/h)")
    # Table 4 row "Discontinuation hazard at PR = 0 (h-1)", h0 = 2.08,
    # SE 0.21. Held on the log scale so it stays positive; the paper
    # reports it untransformed. Results cross-check: "patients with a
    # pain relief score of 0 have a hazard of 2.08, and therefore a 50%
    # chance of requiring rescue medication within 20 min";
    # log(2)/2.08 = 0.333 h = 20.0 min, which also confirms the per-hour
    # (not the per-day of the Figure 5 upper-panel axis label) time base.

    lambda_remd <- 0.201
    label("Fractional decrease in the rescue-medication hazard per unit increment in pain relief score (unitless)")
    # Table 4 row "Fractional decrease in discontinuation hazard per
    # unit increment in PR", lambda = 0.201, SE 0.011. (The symbol is
    # rendered as "7" by the PDF's symbol font; the row description and
    # the equation-11 definition identify it as lambda.) Enters equation
    # 11 as a POWER of the pain relief score, h = h0 * lambda^PR, not as
    # a linear multiplier: the Results state "because lambda is 0.2,
    # this rescue time increases fivefold for every unit increase in PR
    # score", and 1/0.201 = 4.98. Constrained by construction to (0, 1).

    # ==================================================================
    # ONSET OF MEANINGFUL PAIN RELIEF (MPR) MODEL -- Rohatagi 2008
    # Table 5. Equations 13 to 15, split by whether the patient required
    # rescue medication, and recombined by equations 2 and 3. Table 5
    # reports 95% confidence intervals rather than standard errors; the
    # two variability rows are marked "Not estimated", meaning no
    # interval was computed for them, not that they were fixed, so
    # nothing here is wrapped in fixed().
    # ==================================================================
    logitp0_mpr <- qlogis(0.16)
    label("Logit of the probability of meaningful pain relief on placebo in patients who required rescue medication, logit(P0) (logit units)")
    # Table 5 row "Probability of MPR on placebo (%)", P0 = 16%, 95% CI
    # (10, 26). The paper states its own parameterisation explicitly:
    # "The model parameters are logit(P0), logit(Pmax), and
    # log(D50PMPR). The transformations allows more reliable estimates
    # of parameter precision, taking into account the constraints that
    # P0 and Pmax must be in the interval 0-1, and D50MPR must be
    # positive." qlogis(0.16) = -1.6582; expit(-1.6582) = 0.16 exactly.

    logitpmax_mpr <- qlogis(0.72)
    label("Logit of the maximum achievable probability of meaningful pain relief in patients who required rescue medication, logit(Pmax) (logit units)")
    # Table 5 row "Maximum possible probability of MPR", Pmax = 72%, 95%
    # CI (59, 83). Discussion: the probability "was dose-dependent,
    # ranging between 16% on placebo up to a maximum achievable
    # probability of 72%". qlogis(0.72) = 0.9445.

    ld50_pmpr <- log(8.8)
    label("Log of the apricoxib dose giving half-maximal meaningful-pain-relief probability, D50PMPR (mg)")
    # Table 5 row "Dose at which half maximal MPR is achieved (mg)",
    # D50PMPR = 8.8 mg, 95% CI (3.0, 26.1).

    logitpmpr_noremd <- qlogis(0.982)
    label("Logit of the probability of meaningful pain relief in patients who did not require rescue medication (logit units)")
    # Table 5 row "Probability of MPR (%)" in the "Patient does not
    # require rescue medication" block, PMPR = 98.2%, 95% CI (95.0,
    # 99.3). Dose-independent: "Almost all (98.2%) of the patients who
    # did not require rescue medication had MPR ... This percentage was
    # not dose-dependent". qlogis(0.982) = 4.0011.

    ltr0_mpr <- -0.95
    label("Log of the ratio of onset time of meaningful pain relief to rescue time on placebo, LTR0 (log h/h)")
    # Table 5 row "Logarithm of ratio between TMPR and time of rescue
    # medication on placebo", LTR0 = -0.95, 95% CI (-1.42, -0.48).
    # Results cross-check: "on average TMPR was 39% of the time of
    # rescue medication administration on placebo (calculated as the
    # antilogarithm of LTR0)"; exp(-0.95) = 0.387.

    ltrmax_mpr <- -1.00
    label("Maximum possible dose-driven decrease in the log time ratio, LTRmax (log h/h)")
    # Table 5 row "Logarithm of ratio between TMPR and time of rescue
    # medication, maximum possible decrease", LTRmax = -1.00, 95% CI
    # (-1.52, -0.47). Results cross-check: the ratio decreases "to a
    # minimum possible fraction of 14%"; exp(-0.95 - 1.00) = exp(-1.95)
    # = 0.142.

    ld50_ltr <- log(5.8)
    label("Log of the apricoxib dose giving half the maximal time-ratio change, D50LTR (mg)")
    # Table 5 row "Dose at which half maximal TMPR to time of rescue
    # medication ratio is achieved (mg)", D50LTR = 5.8 mg, 95% CI (0.9,
    # 35.8).

    lt0_mpr <- 0.45
    label("Log of the onset time of meaningful pain relief on placebo in patients who did not require rescue medication, LT0 (log h)")
    # Table 5 row "Logarithm of TMPR on placebo", LT0 = 0.45, 95% CI
    # (0.23, 0.67). Results cross-check: "median TMPR was 1.6 h for a
    # placebo dose (calculated as the antilogarithm of LT0)";
    # exp(0.45) = 1.568 h.

    tslope_mpr <- -0.0035
    label("Slope of log onset time of meaningful pain relief on apricoxib dose, LTSlope (log h per mg)")
    # Table 5 row "Slope relating dose to logarithm of TMPR", LTSlope =
    # -0.0035, 95% CI (-0.0053, -0.0018). Results cross-check: TMPR
    # "decreased by 3.5% for every 10-mg increase in dose";
    # 1 - exp(-0.0035 * 10) = 3.44%. Deliberately NOT given an `l`
    # prefix: it is a slope acting ON the log scale, not the logarithm
    # of a slope.

    etaltr0_mpr ~ 0.4096
    # Table 5 row "Residual variability in the logarithm of the time
    # ratio", sigma_LTR = 0.64 (95% CI "Not estimated"); entered as the
    # VARIANCE 0.64^2 = 0.4096. Equation 14 writes this term as
    # epsilon_LTR,i -- subject-indexed -- and the equation-3 text
    # defines sigma as "a normally distributed subject-specific random
    # variable", so it is encoded as inter-individual variability on the
    # intercept LTR0 rather than as residual error. TMPR is observed at
    # most once per patient, so the two are not distinguishable in the
    # source data; see the vignette Assumptions and deviations section.

    etalt0_mpr ~ 0.4761
    # Table 5 row "Residual variability in the logarithm of TMPR",
    # sigma_LT = 0.69 (95% CI "Not estimated"); entered as the VARIANCE
    # 0.69^2 = 0.4761. Equation 15 writes this term as epsilon_LT,i and
    # its defining sentence calls it "normally distributed
    # interindividual variability with mean 0 and standard deviation
    # sLT", so the inter-individual reading is the paper's own for this
    # branch. Encoded on the intercept LT0.
  })

  model({
    # ==================================================================
    # 1. PHARMACOKINETIC LAYER (Kastrissios 2006).
    #
    #    Reproduced verbatim from modellib('Kastrissios_2006_apricoxib')
    #    so that this file simulates the concentration that drives
    #    equation 7 without an external input. Rohatagi 2008 Methods
    #    summarise it as "an open two-compartment model with first-order
    #    absorption, an absorption lag time (median 14 min) and
    #    first-order elimination".
    # ==================================================================

    # Per-dose evening indicator, Kastrissios 2006 equation 6 ("PM is an
    # indicator variable taking on the value of 0 for daytime doses and
    # 1 for evening doses"), derived from the model clock: `t` is hours
    # from the first event, so a dose in the second half of the dosing
    # day is an evening dose. The dental-pain study gave a single dose,
    # so this is 0 throughout an event table that starts at the dose.
    evening <- (t - 24 * floor(t / 24)) >= 12

    # Apparent oral clearance, Kastrissios 2006 equation 7:
    #   CL/F = [(CL/F)_Typ * (1 - Dhi) + (CL/F)_Typ,hi * Dhi]
    #          * exp(Sex * K_CL/F-SEX) * exp(CYPD * K_CL/F-CYP2D6)
    #          * exp(CYPC * K_CL/F-CYP2C9)
    # The bracketed two-value switch is written on the log scale so that
    # it returns exp(lcl) = 34.1 at DOSE_HIGH = 0 and
    # exp(lcl_highdose) = 19.5 at DOSE_HIGH = 1. The source Gender
    # indicator is 1 for MALE, hence (1 - SEXF).
    cl <- exp(lcl + (lcl_highdose - lcl) * DOSE_HIGH +
                e_sexf_cl * (1 - SEXF) +
                e_cyp2d6_pmim_cl * CYP2D6_PM_IM +
                e_cyp2c9_rh_cl * CYP2C9_RH +
                etalcl)

    # Apparent central volume, Kastrissios 2006 equation 8: a power of
    # weight normalised to the 73.3 kg cohort median printed inside the
    # equation itself.
    vc <- exp(lvc + etalvc) * (WT / 73.3)^e_wt_vc

    # Vp/F, Q/F, KA and TLAG carry no covariate effects.
    vp   <- exp(lvp + etalvp)
    q    <- exp(lq  + etalq)
    ka   <- exp(lka + etalka)
    tlag <- exp(ltlag + etaltlag)

    # Relative bioavailability, Kastrissios 2006 equation 6:
    #   Frel = 1 * exp(K_Frel-PM * PM) * D50 / (DOSE + D50)
    # DOSE is the amount of the dose being administered, read off the
    # event record with podo(depot) so it cannot drift out of sync with
    # `amt`. The leading 1 is the authors' non-identifiable absolute
    # bioavailability, so Frel -> 1 as the dose approaches 0 (which is
    # also the value a placebo subject with no dose record takes) and
    # Frel = 0.5 at DOSE = D50 = 221 mg.
    ed50 <- exp(led50)
    frel <- exp(e_evening_fdepot * evening) * ed50 / (podo(depot) + ed50)

    kel <- cl / vc
    k12 <- q / vc
    k21 <- q / vp

    d/dt(depot)       <- -ka * depot
    d/dt(central)     <-  ka * depot - kel * central - k12 * central + k21 * peripheral1
    d/dt(peripheral1) <-  k12 * central - k21 * peripheral1

    f(depot)    <- frel
    alag(depot) <- tlag

    # Apricoxib plasma concentration. Doses are mg and volumes L, so
    # central/vc is mg/L = ug/mL and the factor 1000 converts to the
    # ng/mL scale on which EC50 = 87 ng/mL is reported.
    Cc <- 1000 * central / vc

    # ==================================================================
    # 2. PAIN RELIEF MODEL (Rohatagi 2008 equations 4 to 7, Table 3).
    # ==================================================================

    # Placebo response, equation 6: f_p(t) = Ep * (1 - exp(-Kp * t)).
    # `t` is the model clock; the dental-pain study gave a single dose
    # at the start of the pain-relief assessment schedule, so an event
    # table whose first record is the dose makes `t` the time postdose
    # that the equation intends.
    kplac_pr <- exp(lkplac_pr)
    fplac_pr <- eplac_pr * (1 - exp(-kplac_pr * t))

    # Drug effect, equation 7: f_D(Cp) = Emax * Cp / (Cp + EC50), with
    # Cp the population-PK-model-predicted plasma concentration. Zero
    # for a placebo subject, for whom Cc is 0 throughout.
    ec50_pr  <- exp(lec50_pr)
    fdrug_pr <- emax_pr * Cc / (Cc + ec50_pr)

    # Shared linear predictor of equation 4. The single additive
    # subject-level random effect is carried on the baseline intercept
    # (see the etab1_pr note in ini()).
    lp_pr <- fplac_pr + fdrug_pr

    # Cumulative logits, equation 5.
    b1_i <- b1_pr + etab1_pr
    b2_i <- b1_i + b2b1_pr
    b3_i <- b2_i + b3b2_pr
    b4_i <- b3_i + b4b3_pr

    # Equation 4: P(Y >= k) = expit(beta_k + f_p + f_D + eta).
    pge1_pr <- expit(b1_i + lp_pr)
    pge2_pr <- expit(b2_i + lp_pr)
    pge3_pr <- expit(b3_i + lp_pr)
    pge4_pr <- expit(b4_i + lp_pr)

    # Category probabilities implied by the cumulative form. Non-
    # negative by construction because the incremental thetas are
    # negative, so beta_1 > beta_2 > beta_3 > beta_4 and the cumulative
    # probabilities decrease with k.
    peq0_pr <- 1 - pge1_pr
    peq1_pr <- pge1_pr - pge2_pr
    peq2_pr <- pge2_pr - pge3_pr
    peq3_pr <- pge3_pr - pge4_pr
    peq4_pr <- pge4_pr

    # Expected pain relief score, sum over k of P(Y >= k) for k = 1..4.
    # Its time integral over 0 to T is the paper's TOPAR_T validation
    # metric ("the area under the pain relief score vs. time curve over
    # predefined intervals of time"); the vignette integrates this
    # output rather than adding a bookkeeping ODE state for it.
    score_pr <- pge1_pr + pge2_pr + pge3_pr + pge4_pr

    # ==================================================================
    # 3. RESCUE MEDICATION MODEL (equations 10 to 12, Table 4).
    #
    #    Equation 11 is h = h0 * lambda^PR, where PR is the last
    #    OBSERVED pain relief score, an integer 0 to 4. A continuous-
    #    time solve has a distribution over that score rather than a
    #    realised value, so the hazard integrated here is its
    #    expectation over the equation-4 category probabilities,
    #      E[h] = h0 * sum_k P(Y = k) * lambda^k,
    #    which is exact for the mean hazard (it marginalises the
    #    categorical outcome rather than approximating it by plugging
    #    the mean score into the power law). This is the one place where
    #    the encoding is not a literal transcription of a published
    #    equation; see the vignette Assumptions and deviations section.
    # ==================================================================
    h0_remd   <- exp(lh0_remd)
    haz_remd  <- h0_remd * (peq0_pr +
                            peq1_pr * lambda_remd +
                            peq2_pr * lambda_remd^2 +
                            peq3_pr * lambda_remd^3 +
                            peq4_pr * lambda_remd^4)

    d/dt(cumhaz) <- haz_remd
    cumhaz(0)    <- 0

    # Equation 10, P = 1 - exp(-h * dT), accumulated from time 0: the
    # probability that rescue medication has been required by time t,
    # and its complement, the Kaplan-Meier-style "still on treatment"
    # curve of Figure 2.
    premd_remd <- 1 - exp(-cumhaz)
    sur_remd   <- exp(-cumhaz)

    # Equation 12, T50 = log(2)/h: the time over which half of patients
    # at the current hazard would require rescue medication.
    t50_remd <- log(2) / haz_remd

    # ==================================================================
    # 4. ONSET OF MEANINGFUL PAIN RELIEF (equations 2, 13 to 15,
    #    Table 5). Algebraic in the administered dose.
    # ==================================================================

    # Equation 13, patients who required rescue medication:
    #   P(MPR) = P0 + (Pmax - P0) * Dose / (Dose + D50PMPR).
    # At Dose = 0 this returns P0 = 0.16 exactly.
    p0_mpr      <- expit(logitp0_mpr)
    pmax_mpr    <- expit(logitpmax_mpr)
    d50p_mpr    <- exp(ld50_pmpr)
    pmpr_remd   <- p0_mpr + (pmax_mpr - p0_mpr) *
      DOSE_APRICOXIB_MG / (DOSE_APRICOXIB_MG + d50p_mpr)

    # Patients who did not require rescue medication: dose-independent.
    pmpr_noremd <- expit(logitpmpr_noremd)

    # Equation 2, the mixture over whether rescue medication occurred:
    #   P(MPR) = P(MPR | REMD) * P(REMD) + P(MPR | no REMD) * P(no REMD)
    # with P(REMD) supplied by the rescue-medication sub-model above.
    pmpr <- pmpr_remd * premd_remd + pmpr_noremd * (1 - premd_remd)

    # Equation 14, patients who required rescue medication. The model
    # predicts the RATIO of the onset time to that patient's own rescue
    # time, which is the quantity plotted against dose in the lower
    # right panel of Figure 1; multiply by an individual rescue time to
    # obtain an absolute TMPR.
    d50_ltr_mpr  <- exp(ld50_ltr)
    logratio_mpr <- ltr0_mpr + etaltr0_mpr +
      ltrmax_mpr * DOSE_APRICOXIB_MG / (DOSE_APRICOXIB_MG + d50_ltr_mpr)
    ratio_mpr    <- exp(logratio_mpr)

    # Equation 15, patients who did not require rescue medication:
    #   log(TMPR) = LT0 + LTSlope * Dose + eps.
    logtmpr_mpr <- lt0_mpr + etalt0_mpr + tslope_mpr * DOSE_APRICOXIB_MG
    tmpr_mpr    <- exp(logtmpr_mpr)

    # ==================================================================
    # 5. Observation. The only endpoint carrying a published residual
    #    error is the apricoxib plasma concentration (Kastrissios 2006
    #    equation 3, proportional). The pain-relief endpoint is
    #    categorical -- its likelihood is the multinomial implied by the
    #    equation-4 cumulative probabilities, which has no residual-error
    #    term to attach -- and the rescue-medication and onset-time
    #    endpoints are a time-to-event hazard and a subject-level
    #    log-normal draw. Those quantities are exposed as derived
    #    outputs above rather than being given fabricated residual
    #    errors; every rxode2 solve returns them as columns.
    # ==================================================================
    Cc ~ prop(propSd)
  })
