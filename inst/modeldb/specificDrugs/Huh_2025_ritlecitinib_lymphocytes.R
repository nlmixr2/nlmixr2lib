Huh_2025_ritlecitinib_lymphocytes <- function() {
  description <- paste(
    "Semi-mechanistic PK/PD model of the absolute lymphocyte count during",
    "oral ritlecitinib (a JAK3/TEC-family kinase inhibitor) treatment in",
    "healthy volunteers and adolescent and adult patients with alopecia",
    "areata. Friberg 2002 myelosuppression structure: a self-renewing",
    "proliferating pool (prol), three transit compartments and the",
    "circulating lymphocyte pool (circ), with kprol = ktr = kcirc =",
    "(3 + 1)/MTT, a (circ0/circ)^gamma feedback on proliferation and an",
    "inhibitory Emax effect of the plasma ritlecitinib concentration on",
    "proliferation. Emax is fixed to 1 for a typical subject and scaled by",
    "the individual baseline count, Emax = (circ0/1.65)^-1.6, so subjects",
    "with a lower baseline are more sensitive; the drug effect is capped",
    "at 1. Age (power, referenced to 45 years) and female sex (+6.09%)",
    "act on the baseline count circ0, the only parameter with",
    "between-subject variability. EC50 (25,800 ng/mL) lies far above the",
    "therapeutic concentrations, so the effect is almost linear in",
    "concentration and the very small feedback exponent (gamma = 0.0154)",
    "amplifies a small proliferation inhibition into a sustained",
    "reduction of the steady-state count. The plasma concentration is",
    "generated by the embedded final ritlecitinib population PK model of",
    "Wojciechowski 2023 (two compartments, first-order absorption,",
    "peripheral-concentration autoinhibition of CL/F and F), whose",
    "parameters are fixed because Huh 2025 drove the PD model with the",
    "empirical Bayes PK estimates from that model."
  )

  reference <- paste(
    "Huh Y, Qiu R, Prybylski J, Wojciechowski J, Wang Y, Purohit VS.",
    "Comprehensive Safety Exposure-Response Analysis to Support",
    "Ritlecitinib Dose Selection. CPT Pharmacometrics Syst Pharmacol.",
    "2025;14(6):1108-1118. doi:10.1002/psp4.70030. PK layer from",
    "Wojciechowski J, Purohit VS, Huh Y, Banfield C, Nicholas T.",
    "Evolution of Ritlecitinib Population Pharmacokinetic Models During",
    "Clinical Drug Development. Clin Pharmacokinet. 2023;62(12):1765-1779.",
    "doi:10.1007/s40262-023-01318-3 (final-model column of Table 2; see",
    "modellib('Wojciechowski_2023_ritlecitinib_final')).",
    sep = " "
  )

  vignette <- "Huh_2025_ritlecitinib_safety"

  units <- list(
    time = "h",
    dosing = "mg",
    concentration = "ng/mL",
    lymphocytes = "10^9/L"
  )

  compartmentData <- list(
    depot = list(analyte = "ritlecitinib", units = "mg", specimen = "administration site", verified = TRUE),
    central = list(analyte = "ritlecitinib", units = "mg", specimen = "plasma", verified = TRUE),
    peripheral1 = list(analyte = "ritlecitinib", units = "mg", specimen = "tissue", verified = TRUE),
    prol = list(analyte = "lymphocyte progenitor cells", units = "10^9/L", specimen = "tissue", verified = TRUE),
    transit1 = list(analyte = "maturing lymphocytes", units = "10^9/L", specimen = "tissue", verified = TRUE),
    transit2 = list(analyte = "maturing lymphocytes", units = "10^9/L", specimen = "tissue", verified = TRUE),
    transit3 = list(analyte = "maturing lymphocytes", units = "10^9/L", specimen = "tissue", verified = TRUE),
    circ = list(analyte = "lymphocytes", units = "10^9/L", specimen = "whole blood", verified = TRUE)
  )

  covariateData <- list(
    WT = list(
      description = "Baseline total body weight; allometrically scales CL/F, Q/F, Vc/F and Vp/F of the embedded PK model",
      units = "kg",
      type = "continuous",
      reference_category = NULL,
      notes = "Time-fixed baseline weight. Reference 70 kg with fixed exponents 0.75 on CL/F and Q/F and 1 on Vc/F and Vp/F (Wojciechowski 2023 Table 2 footnote). Only used by the PK layer; Huh 2025 did not test weight on the lymphocyte parameters.",
      source_name = "BWT"
    ),
    DIS_ALOPECIA_AREATA = list(
      description = "Alopecia areata patient indicator (PK layer)",
      units = "(binary)",
      type = "binary",
      reference_category = "0 (healthy volunteer)",
      notes = "Carries the -26.0% effect on CL/F of the Wojciechowski 2023 final PK model and switches on the inflammatory-disease scaling of the PK IIV magnitudes. The Huh 2025 lymphocyte dataset pooled 80 healthy volunteers (first-in-human study B7981001) with 1878 alopecia areata patients (studies B7931005, B7981015 and B7981032). Not a covariate on the lymphocyte parameters.",
      source_name = "PTST"
    ),
    AGE = list(
      description = "Age at baseline",
      units = "years",
      type = "continuous",
      reference_category = NULL,
      notes = "Power effect on the baseline lymphocyte count, circ0 = 1.65 * (AGE/45)^-0.153 (Huh 2025 Results, Longitudinal PK/PD Model of Lymphocyte Count; Table 2 row 'Effect of Age on Circ 0'). Analysis population aged 12-72 years (Table 3 age tertiles 12-17, 18-50 and 51-72 years).",
      source_name = "Age"
    ),
    SEXF = list(
      description = "Female sex indicator",
      units = "(binary)",
      type = "binary",
      reference_category = "0 (male)",
      notes = "Fractional effect on the baseline lymphocyte count, circ0 multiplied by (1 + 0.0609 * SEXF); the Results state that 'female patients have 6% higher baseline than males' (Table 2 row 'Effect of Female on Circ 0').",
      source_name = "Female"
    )
  )

  # Wojciechowski 2023 also carries a severe-renal-impairment effect on F.
  # The lymphocyte dataset contained no renal-impairment participants, so it
  # is documented here and not carried.
  covariatesDataExcluded <- list(
    RENALIMP_SEV = list(
      description = "Severe renal impairment indicator (Wojciechowski 2023 final PK model)",
      units = "(binary)",
      type = "binary",
      reference_category = "0 (normal renal function)",
      notes = "Effect of +35.3% on F in the final PK model. Not carried because the Huh 2025 lymphocyte analysis population (healthy volunteers and alopecia areata patients) contained no renal-impairment participants; all subjects have RENALIMP_SEV = 0."
    )
  )

  population <- list(
    species = "human",
    n_subjects = 1958L,
    n_studies = 4L,
    age_range = "12-72 years",
    disease_state = "Alopecia areata patients (1878; adolescents and adults) and healthy volunteers (80)",
    dose_range = "Healthy volunteers: single doses 5-800 mg and multiple doses 50-400 mg QD and 100-200 mg BID (B7981001). Alopecia areata: 10, 30 and 50 mg QD with or without a 200 mg QD 4-week loading dose, and 200/50 mg QD (B7931005, B7981015, B7981032).",
    regions = "Global (phase 2/3 alopecia areata programme)",
    notes = "Huh 2025 Results 'Longitudinal PK/PD Model of Lymphocyte Count': 1958 subjects (80 healthy volunteers and 1878 alopecia areata patients) from the first-in-human study and the phase 2/3 alopecia areata studies (Table 1). Sex and weight distributions of the lymphocyte dataset are not reported. Fitted with NONMEM 7.5.0, FOCE-I, with the individual PK parameters fixed to their empirical Bayes estimates from the Wojciechowski 2023 final model (Supplement 2 control stream)."
  )

  ini({
    # ----- PK layer: Wojciechowski 2023 final model, fixed -----
    # Huh 2025 Methods: 'Ct is drug concentration at time t derived using the
    # Empirical Bayes estimates (EBE) of individual PK parameters from the
    # population PK model [11]'. Values copied from
    # Wojciechowski_2023_ritlecitinib_final (Table 2 final-model column).
    lcl <- fixed(log(107)); label("Apparent clearance CL/F at 70 kg, uninhibited (L/h)") # Wojciechowski 2023 Table 2 final: 107
    lvc <- fixed(log(151)); label("Apparent central volume Vc/F at 70 kg (L)") # Wojciechowski 2023 Table 2 final: 151
    lq <- fixed(log(0.297)); label("Apparent inter-compartmental clearance Q/F at 70 kg (L/h)") # Wojciechowski 2023 Table 2 final: 0.297
    lvp <- fixed(log(4.87)); label("Apparent peripheral volume Vp/F at 70 kg (L)") # Wojciechowski 2023 Table 2 final: 4.87
    lka <- fixed(log(7.91)); label("First-order absorption rate constant ka (1/h)") # Wojciechowski 2023 Table 2 final: 7.91
    imax <- fixed(-0.452); label("Maximum non-stationary fractional effect Imax,P on CL/F and F (unitless)") # Wojciechowski 2023 Table 2 final: -0.452
    lic50 <- fixed(log(16.5)); label("Peripheral concentration giving half the maximum non-stationary effect IC50,P (ng/mL)") # Wojciechowski 2023 Table 2 final: 16.5
    e_wt_cl_q <- fixed(0.75); label("Allometric WT exponent shared by CL/F and Q/F (unitless)") # Wojciechowski 2023 Table 2 footnote
    e_wt_vc_vp <- fixed(1.00); label("Allometric WT exponent shared by Vc/F and Vp/F (unitless)") # Wojciechowski 2023 Table 2 footnote
    e_alopecia_areata_cl <- fixed(-0.260); label("Fractional effect of alopecia areata on CL/F (unitless)") # Wojciechowski 2023 Table 2 final: -0.260
    e_inflam_iiv_cl <- fixed(1.61); label("Fractional effect of inflammatory disease on the SD of IIV on CL/F (unitless)") # Wojciechowski 2023 Table 2 final: 1.61
    e_inflam_iiv_vc <- fixed(1.43); label("Fractional effect of inflammatory disease on the SD of IIV on Vc/F (unitless)") # Wojciechowski 2023 Table 2 final: 1.43

    # ----- Lymphocyte PD (Huh 2025 Table 2, 'Lymphocyte PK/PD model') -----
    lcirc0 <- log(1.65); label("Baseline circulating lymphocyte count circ0 for a 45-year-old male (10^9/L)") # Table 2: Circ 0 = 1.65 (95% CI 1.59-1.71)
    e_age_circ0 <- -0.153; label("Power exponent of AGE/45 on circ0 (unitless)") # Table 2: Effect of Age on Circ 0 = -0.153 (95% CI -0.192 to -0.107); Results: circ0 = population circ0 x (Age/45 years)^-0.153
    e_sexf_circ0 <- 0.0609; label("Fractional effect of female sex on circ0 (unitless)") # Table 2: Effect of Female on Circ 0 = 0.0609 (95% CI 0.0244-0.0968); Results: 'female patients have 6% higher baseline'
    lmtt <- log(3.12); label("Mean transit time through the three-transit maturation chain MTT (day)") # Table 2: MTT = 3.12 days (95% CI 1.94-3.23)
    lgamma <- log(0.0154); label("Feedback exponent gamma on (circ0/circ) (unitless)") # Table 2: gamma = 0.0154 (95% CI 0.00911-0.0165)
    lemax <- fixed(log(1)); label("Maximum fractional inhibition of proliferation Emax at the population circ0 (unitless)") # Table 2: Emax = 1 fix
    e_circ0_emax <- -1.6; label("Power exponent of the individual circ0 / population circ0 on Emax (unitless)") # Table 2: Effect of Circ 0 on E max = -1.6 (95% CI -1.85 to -1.39); Results: Emax = population Emax x (circ0/population circ0)^-1.6
    lec50 <- log(25800); label("Plasma ritlecitinib concentration giving half of Emax, EC50 (ng/mL)") # Table 2: EC 50 = 25,800 ng/mL (95% CI 24,400-40,300)

    # ----- PK IIV (fixed; Wojciechowski 2023 final, %CV = 100*omega) -----
    etalcl ~ fixed(0.035344) # Wojciechowski 2023 Table 2 final: 18.8 percent-CV -> 0.188^2
    etalvc ~ fixed(0.013225) # Wojciechowski 2023 Table 2 final: 11.5 percent-CV -> 0.115^2

    # ----- PD IIV -----
    etalcirc0 ~ 0.0493 # Table 2: omega^2 CIRC0 = 0.0493 (95% CI 0.0439-0.0555); Supplement 2 $OMEGA on ETA(1), CIRC0 = POPCIRC0 * EXP(ETA(1))

    # ----- Residual error -----
    propSd <- 0.187; label("Proportional residual SD on the lymphocyte count (fraction)") # Table 2: Residual Error = 0.187 (95% CI 0.185-0.189); Supplement 2 $ERROR W = IPRE * RUVPRO with $SIGMA 1 FIX, so RUVPRO is the SD
  })
  model({
    # ----- PK layer (Wojciechowski 2023 final model) -----
    ref_wt <- 70
    inflam <- DIS_ALOPECIA_AREATA
    covvarcl <- 1 + e_inflam_iiv_cl * inflam
    covvarvc <- 1 + e_inflam_iiv_vc * inflam

    cl <- exp(lcl + etalcl * covvarcl) * (WT / ref_wt)^e_wt_cl_q *
      (1 + e_alopecia_areata_cl * DIS_ALOPECIA_AREATA)
    vc <- exp(lvc + etalvc * covvarvc) * (WT / ref_wt)^e_wt_vc_vp
    q <- exp(lq) * (WT / ref_wt)^e_wt_cl_q
    vp <- exp(lvp) * (WT / ref_wt)^e_wt_vc_vp
    ka <- exp(lka)
    # IC50 in ng/mL; peripheral concentration below is in mg/L.
    ic50 <- exp(lic50) / 1000

    # Autoinhibition by the peripheral concentration: CL/F is multiplied by
    # autoinh and the absorbed fraction by (2 - autoinh) (Supplement 2 $DES,
    # AUTOINH and INHF).
    autoinh <- 1 + imax * (peripheral1 / vp) / (ic50 + peripheral1 / vp)

    d/dt(depot) <- -ka * depot
    d/dt(central) <- ka * depot * (2 - autoinh) -
      q * (central / vc) + q * (peripheral1 / vp) -
      cl * autoinh * (central / vc)
    d/dt(peripheral1) <- q * (central / vc) - q * (peripheral1 / vp)

    # mg/L -> ng/mL
    Cc <- central / vc * 1000

    # ----- Lymphocyte PD (Huh 2025 Equation 2; Supplement 2 $PK/$DES) -----
    circ0_pop <- exp(lcirc0)
    circ0 <- circ0_pop * (AGE / 45)^e_age_circ0 * (1 + e_sexf_circ0 * SEXF) *
      exp(etalcirc0)
    # Emax = POPEMAX * (CIRC0/POPCIRC0)^CIRC0EMAX with POPCIRC0 = THETA(2),
    # the reference-subject value, not the covariate-adjusted typical value.
    emax <- exp(lemax) * (circ0 / circ0_pop)^e_circ0_emax
    ec50 <- exp(lec50)
    gamma <- exp(lgamma)

    # ntrans = 3 (fixed): ktr = kprol = kcirc = (ntrans + 1)/MTT; MTT in days.
    mtt <- exp(lmtt) * 24
    ktr <- 4 / mtt

    # Supplement 2 $DES: IF (EDRUG.GT.1) EDRUG = 1.
    edrug <- min(emax * Cc / (ec50 + Cc), 1)
    feedback <- (circ0 / circ)^gamma

    d/dt(prol) <- ktr * prol * (1 - edrug) * feedback - ktr * prol
    d/dt(transit1) <- ktr * prol - ktr * transit1
    d/dt(transit2) <- ktr * transit1 - ktr * transit2
    d/dt(transit3) <- ktr * transit2 - ktr * transit3
    d/dt(circ) <- ktr * transit3 - ktr * circ

    # All lymphocyte compartments start at the individual baseline.
    prol(0) <- circ0
    transit1(0) <- circ0
    transit2(0) <- circ0
    transit3(0) <- circ0
    circ(0) <- circ0

    circ ~ prop(propSd)
  })
}
