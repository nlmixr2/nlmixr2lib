Qian_2025_tetrahydrocannabinol <- function() {
  description <- paste(
    "Heart-rate pharmacodynamic model of delta-9-tetrahydrocannabinol (THC)",
    "and its active metabolite 11-hydroxy-THC (11-OH-THC) in healthy adults,",
    "the PD layer of the Qian 2025 PBPK-PD model. Each analyte's total heart",
    "concentration feeds its own effect compartment (THC: separate transfer",
    "and loss rate constants k1e and ke0; 11-OH-THC: a single equilibration",
    "rate constant), and the sum of the two effect-compartment concentrations",
    "drives one hyperbolic Emax increase of heart rate relative to the",
    "pre-dose baseline, with Emax and EC50 shared by both analytes. Only this",
    "PD layer is reproduced here: the PBPK layer is a Simcyp whole-body model",
    "whose organ volumes, blood flows and tissue partition coefficients are",
    "platform outputs the paper does not print, so the THC and 11-OH-THC",
    "heart concentrations are supplied by the user as time-varying covariates",
    "(umol/L) rather than generated by a PK model in this file. Inter-",
    "individual variability on Emax and EC50 is taken from Strougo 2008; no",
    "residual-error model is reported, so it is zero.",
    sep = " "
  )
  reference <- paste(
    "Qian L, Zhou Z. (2025).",
    "Quantifying Heart Rate Changes After Delta-9-Tetrahydrocannabinol",
    "Administration Using a PBPK-PD Model in Healthy Adults.",
    "Pharmaceutics 17(2):237. doi:10.3390/pharmaceutics17020237.",
    "Inter-individual variability of Emax and EC50 from Strougo A et al.",
    "(2008) J Psychopharmacol 22:717-726, doi:10.1177/0269881108089870",
    "(reference 20 of Qian 2025).",
    sep = " "
  )
  vignette <- "Qian_2025_tetrahydrocannabinol"
  units <- list(
    time = "h",
    dosing = "(not applicable; THC and 11-OH-THC heart concentrations are supplied as covariates, not as dose records)",
    concentration = "umol/L (THC and 11-OH-THC heart and effect-compartment concentrations; hr is in beats/min)"
  )

  covariateData <- list(
    CHEART_TETRAHYDROCANNABINOL_UM = list(
      description = "Total THC concentration in the heart tissue compartment (umol/L), the driver of the THC effect compartment",
      units = "umol/L",
      type = "continuous",
      reference_category = NULL,
      notes = paste(
        "Qian 2025 Equation 3 and the supplementary Lua code",
        "('Substrate heart concentration'): the effect compartment is fed by",
        "the TOTAL THC concentration in the heart compartment of the",
        "authors' Simcyp whole-body PBPK model, which the paper selected over",
        "plasma and brain as the driving compartment (Results). EC50 is in",
        "umol/L (Table 1), so a concentration in ng/mL must be divided by",
        "the THC molecular weight 314.46 g/mol. In the source the heart",
        "profile is a Simcyp output (Qian 2025, Clin Transl Sci 18:e70119;",
        "oral fa 0.45 and ka 0.7 1/h, inhaled lung fa 0.05-0.9 and lung ka",
        "12 or 200 1/h, Table 1 and supplementary Table S1) and is not",
        "reproducible from the publication; the paper notes the predicted",
        "heart and plasma THC profiles are similar (supplementary Figure S2).",
        "Set to 0 for drug-free records."
      ),
      source_name = "C_THC (Qian 2025 Equation 3); 'Substrate heart concentration' (supplementary Lua code)"
    ),
    CHEART_11OH_TETRAHYDROCANNABINOL_UM = list(
      description = "Total 11-hydroxy-THC concentration in the heart tissue compartment (umol/L), the driver of the 11-OH-THC effect compartment",
      units = "umol/L",
      type = "continuous",
      reference_category = NULL,
      notes = paste(
        "Qian 2025 Equation 1 and the supplementary Lua code",
        "('Sub Pri Metabolite1 heart concentration'): the TOTAL 11-OH-THC",
        "concentration in the heart compartment of the authors' Simcyp",
        "PBPK model, formed from THC or given directly as an intravenous",
        "dose. In umol/L: divide a concentration in ng/mL by the 11-OH-THC",
        "molecular weight 330.46 g/mol. The paper does not print any",
        "11-OH-THC concentration profile. Set to 0 for drug-free records."
      ),
      source_name = "C_11-OH-THC (Qian 2025 Equation 1); 'Sub Pri Metabolite1 heart concentration' (supplementary Lua code)"
    ),
    HR_BL = list(
      description = "Pre-dose baseline heart rate (beats/min)",
      units = "beats/min",
      type = "continuous",
      reference_category = NULL,
      notes = paste(
        "Qian 2025 Equation 4: 'Baseline is the baseline of the heart rate,",
        "which is the observed heart rate from the studies measured before",
        "THC dosing'; the closest observed mean pre-dose heart rate of each",
        "study was used, with no inter-individual variability (Discussion).",
        "The tachycardia-risk simulations used 70 beats/min (Methods 2.6)."
      ),
      source_name = "Baseline (Qian 2025 Equation 4)"
    )
  )

  compartmentData <- list(
    effect = list(
      analyte = "delta-9-tetrahydrocannabinol",
      units = "umol/L",
      specimen = "not applicable",
      verified = TRUE
    ),
    effect_11oh = list(
      analyte = "11-hydroxy-delta-9-tetrahydrocannabinol",
      units = "umol/L",
      specimen = "not applicable",
      verified = TRUE
    )
  )

  population <- list(
    species = "human",
    n_subjects = NA_integer_,
    n_studies = 30L,
    age_range = "healthy adults (per-study demographics not tabulated); tachycardia-risk simulations used virtual adults aged 18-65 years",
    weight_range = "not reported",
    sex_female_pct = NA_real_,
    race_ethnicity = "not reported",
    disease_state = "healthy adult volunteers; occasional cannabis users only (chronic users with a non-zero baseline THC concentration were excluded)",
    dose_range = "THC 2-69.4 mg (intravenous, oral and inhaled) and 11-OH-THC 2.27 mg or 46.99 ug/kg intravenous, single doses and inhaled dose series",
    regions = "not reported (studies taken from the published literature)",
    notes = paste(
      "Observed mean heart-rate profiles were digitised from 30 published",
      "clinical trials comprising 42 THC dosing regimens plus two",
      "intravenous 11-OH-THC regimens (Methods 2.2; supplementary Table S1).",
      "The PD parameters were optimised on one intravenous study that gave",
      "both THC and 11-OH-THC (Perez-Reyes 1973), verified on one oral",
      "(Kirk 1998) and one inhaled (Zuurman 2008) study, and validated on",
      "the rest. Model development used a Simcyp virtual healthy-adult",
      "population (ten trials per study design); the number of real",
      "individuals behind the digitised means is not reported."
    )
  )

  ini({
    # ------------------------------------------------------------------
    # Qian 2025 Equations 1, 3 and 4, and the supplementary Lua code:
    #
    #   dCe_THC/dt   = k1e_THC * C_THC - ke0_THC * Ce_THC                (3)
    #   dCe_11OH/dt  = ke0_11OH * (C_11OH - Ce_11OH)              (1; Lua)
    #   HR = Baseline * (1 + Emax/100 * (Ce_THC + Ce_11OH) /
    #                         (EC50 + Ce_THC + Ce_11OH))         (4; Lua)
    #
    # Values are Table 1 (PD rows); the Lua code repeats them. Table 1
    # reports no standard errors.
    # ------------------------------------------------------------------

    lk1e_thc <- log(4)
    label("THC transfer rate constant from the heart compartment into its effect compartment k1e (1/h)")
    # Table 1, 'k1e (/h)', THC column = 4 (Optimized); Lua 'k1e1' = 4

    lke0_thc <- log(6.5)
    label("THC effect-compartment loss rate constant ke0 (1/h)")
    # Table 1, 'ke0 (/h)', THC column = 6.5 (Optimized); Lua 'ke01' = 6.5

    lke0_11oh <- log(15)
    label("11-OH-THC effect-compartment equilibration rate constant, k1e = ke0 (1/h)")
    # Table 1, 'k1e (/h)' and 'ke0 (/h)', 11-OH-THC column = 15 and 15
    # (Optimized); Lua 'ke02' = 15 used for both terms,
    # ke02 * (C_OHTHC - C_OHTHCE). Methods 2.4: 'k1e and ke0 were assumed
    # to be the same unless the optimized values could not capture the
    # observations'.

    lemax <- log(105)
    label("Maximum increase in heart rate from baseline Emax (% of baseline)")
    # Table 1, 'Emax (%)' = 105 (11-OH-THC: Optimized; THC: 'Same as
    # 11-OH-THC'); Lua 'Emax' = 105, divided by 100 in the heart-rate line

    lec50 <- log(0.15)
    label("Summed THC + 11-OH-THC effect-compartment concentration for half-maximal increase EC50 (umol/L)")
    # Table 1, 'EC50 (uM)' = 0.15 (11-OH-THC: Optimized; THC: 'Same as
    # 11-OH-THC'); Lua 'EC50' = 0.15

    # IIV: Table 1 'CV Emax (%)' = 32 and 'CV EC50 (%)' = 79, both taken
    # from Strougo 2008 (reference 20), hence fixed. Encoded as log-normal
    # variances log(1 + CV^2); the Simcyp Lua code samples a truncated
    # normal (TRUNCATED_NORMAL_CV) whose truncation bounds are a platform
    # setting not printed in the paper.
    etalemax ~ fixed(0.097490)
    etalec50 ~ fixed(0.484954)

    addSd <- fixed(0)
    label("Additive residual SD on heart rate (beats/min; zero - no residual-error model is reported)")
  })

  model({
    k1e_thc <- exp(lk1e_thc)
    ke0_thc <- exp(lke0_thc)
    ke0_11oh <- exp(lke0_11oh)
    emax <- exp(lemax + etalemax)
    ec50 <- exp(lec50 + etalec50)

    d/dt(effect) <- k1e_thc * CHEART_TETRAHYDROCANNABINOL_UM - ke0_thc * effect
    d/dt(effect_11oh) <- ke0_11oh * (CHEART_11OH_TETRAHYDROCANNABINOL_UM - effect_11oh)

    ce_sum <- effect + effect_11oh
    pchg_hr <- emax * ce_sum / (ec50 + ce_sum)
    hr <- HR_BL * (1 + pchg_hr / 100)

    hr ~ add(addSd)
  })
}
