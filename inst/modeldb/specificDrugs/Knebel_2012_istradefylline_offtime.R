Knebel_2012_istradefylline_offtime <- function() {
  description <- paste0(
    "Population exposure-response model for the percentage of awake time ",
    "spent in the OFF state in adults with Parkinson disease on ",
    "levodopa/carbidopa with motor response complications, treated with ",
    "adjunctive oral istradefylline (KW-6002, a selective adenosine A2A ",
    "receptor antagonist). Knebel 2012 Table II 'Final Model' full ",
    "covariate model. Percentage OFF time is the sum of two additive ",
    "components: a disease-progression/placebo-response (DP-PR) term that ",
    "is an Emax function of time in the study proportional to the ",
    "individual baseline percentage OFF time E0, and an istradefylline ",
    "effect that is an Emax function of the individual predicted ",
    "istradefylline AUC at steady state. There is no PK layer in this ",
    "model: exposure enters as the time-fixed AUC_ISTRA data covariate ",
    "(ng*hr/mL), which the source paper generated from a companion ",
    "population PK model (Knebel 2012 reference 6). E0, the maximum DP-PR ",
    "effect and the maximum istradefylline effect each carry a power-model ",
    "covariate set (UPDRS subscale 2 score, time since onset of motor ",
    "complications, baseline OFF time, and four concomitant-medication ",
    "indicators). Between-subject variability is additive on the linear ",
    "scale of E0, EmaxP and EmaxI, with E0 and EmaxP correlated. Residual ",
    "error is combined exponential-plus-additive on the percentage scale. ",
    "Companion models from the same paper cover the dyskinesia, dizziness ",
    "and nausea adverse-event endpoints."
  )
  reference <- paste(
    "Knebel W, Rao N, Uchimura T, Mori A, Fisher J, Gastonguay MR, Chaikin P.",
    "Population pharmacokinetic-pharmacodynamic analysis of istradefylline",
    "in patients with Parkinson disease.",
    "J Clin Pharmacol. 2012;52(10):1468-1481.",
    "doi:10.1177/0091270011420566.",
    "The individual istradefylline AUC at steady state that drives this",
    "model was generated by the upstream population PK model of",
    "Knebel W, Rao N, Uchimura T, et al., Population pharmacokinetic",
    "analysis of istradefylline in healthy subjects and in patients with",
    "Parkinson's disease, J Clin Pharmacol (published online ahead of",
    "print 3 March 2010; Knebel 2012 reference 6). That PK model is not",
    "part of this file and is not currently in nlmixr2lib; AUC_ISTRA must",
    "be supplied as a data covariate.",
    sep = " "
  )
  vignette <- "Knebel_2012_istradefylline"

  # The source paper places the between-subject random effects ADDITIVELY on
  # the linear scale of E0, EmaxP and EmaxI (Knebel 2012 equations for E0i,
  # EmaxPi and EmaxIi each end in "+ etaE0", "+ etaEmaxP", "+ etaEmaxI"), and
  # the reported variances confirm it: omega^2_E0 = 98.1 gives SD 9.90 on a
  # parameter whose typical value is 39.5 percent, and omega^2_EmaxP = 0.118
  # gives SD 0.343 on a typical value of -0.147, i.e. the random effect is
  # large enough to flip the sign -- impossible under a log-normal. EmaxP and
  # EmaxI are negative, so they cannot be log-transformed at all. The
  # canonical eta + l<param> pairing therefore does not apply; declare the
  # eta names as paper-specific so checkModelConventions() accepts them.
  # Same shape as Lee_2011_parkinson_progression.R (etaslope / etasymeff).
  # See references/parameter-names.md "Paper-specific etas".
  #
  # NOTE the Methods text says "All interindividual error terms were
  # described by an exponential error model, or log-normal parameter
  # distribution, unless otherwise indicated." The printed equations ARE the
  # indication otherwise, and the reported variance magnitudes agree with
  # them; per skill policy a text-versus-printed-equation conflict is
  # resolved in favour of the equation.
  paper_specific_etas <- c("etae0", "etaemax_dppr", "etaemax_drug")

  units <- list(
    time          = "day",
    dosing        = "(none; istradefylline exposure enters as the AUC_ISTRA covariate in ng*hr/mL, not as dosing events)",
    concentration = "(percent of awake time spent in the OFF state; observation pctofftime)"
  )

  covariateData <- list(
    AUC_ISTRA = list(
      description        = "Individual predicted istradefylline area under the plasma concentration-time curve at steady state over one dosing interval (24 h; istradefylline is dosed once daily).",
