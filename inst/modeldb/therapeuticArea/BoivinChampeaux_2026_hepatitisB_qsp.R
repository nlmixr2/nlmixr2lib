        (1 - (Hep_LV + iHep1_LV + iHep2_LV) / Hep_0) -
      NK_lysis_rate_Hep / V_LV                                                           # Eq. S1

    d/dt(intHBV_LV) <- -f_cccDNA * inf_flux -
      kdeg_HBV_LV * intHBV_LV +
      HBV_int_rate_tot -
      (1 - f_cccDNA) * inf_flux                                                          # Eq. S2

    d/dt(iHep1_LV) <- -CD8_lysis_rate_iHep1 / V_LV -
      NK_lysis_rate_iHep1 / V_LV -
      kdeath_iHep * iHep1_LV +
      f_cccDNA * inf_flux -
      kprol_iHep * iHep1_LV *
        (1 - (Hep_LV + iHep1_LV + iHep2_LV) / MAX_Hep_LV)                                # Eq. S3

    d/dt(iHep2_LV) <- -NK_lysis_rate_iHep2 / V_LV +
      (1 - f_cccDNA) * inf_flux +
      kprol_iHep * iHep2_LV *
        (1 - (Hep_LV + iHep1_LV + iHep2_LV) / MAX_Hep_LV) -
      kdeath_iHep * iHep2_LV -
      CD8_lysis_rate_iHep2 / V_LV                                                        # Eq. S4

    d/dt(expHBV_LV) <- -kdeg_HBV_LV * expHBV_LV +
      ksyn_HBV_cccDNA * iHep1_LV * (1 - HBV_rep_inhibition) -
      kLV_PL_HBV * expHBV_LV                                                             # Eq. S5

    # =====================================================================
    # 2. LIVER - innate immune system (Eq. S6-S12)
    # =====================================================================
    d/dt(KCn_LV) <- -KC_activation * KCn_LV -
      kdeath_KCnaive * KCn_LV +
      kprol_KC * KCn_LV * (1 - (KCn_LV + KCa_LV) / MAX_KC_LV)                            # Eq. S6

    d/dt(KCa_LV) <- KC_activation * KCn_LV - kdeath_KCact * KCa_LV                       # Eq. S7

    d/dt(NKn_LV) <- kPL_LV_NK * NKn_PL * (V_PL / V_LV) -
      kdeath_NKnaive * NKn_LV -
      NK_activation_LV * NKn_LV                                                          # Eq. S8

    d/dt(NKbr_LV) <- NK_activation_LV * NKn_LV -
      kdeath_NKact * NKbr_LV -
      kmature_NK_LV * NKbr_LV                                                            # Eq. S9

    d/dt(NKdim_LV) <- kmature_NK_LV * NKbr_LV - kdeath_NKact * NKdim_LV                  # Eq. S10

    # Eq. S11 writes the naive-mDC death constant as kdeath_DCnaive; Table
    # S3 tabulates kdeath_mDCnaive and kdeath_pDCnaive, both 0.23/day, and
    # this state is the myeloid one.
    d/dt(mDCn_LV) <- kPL_LV_DC * mDCn_PL * (V_PL / V_LV) -
      mDC_activation * mDCn_LV -
      kdeath_mDCnaive * mDCn_LV                                                          # Eq. S11

    d/dt(mDCa_LV) <- mDC_activation * mDCn_LV -
      kdeath_mDCact * mDCa_LV -
      kLV_LN_DC * mDCa_LV                                                                # Eq. S12

    # =====================================================================
    # 3. LIVER - adaptive immune system (Eq. S13-S20)
    # =====================================================================
    d/dt(pCD8_LV) <- kPL_LV_CD8 * pCD8_PL * (V_PL / V_LV) -
      pCD8_act_LV * pCD8_LV -
      kdeath_pCD8 * pCD8_LV                                                              # Eq. S13

    d/dt(eCD8_LV) <- -kdeath_eCD8 * eCD8_LV +
      pCD8_act_LV * pCD8_LV +
      kprol_CD8_LV * eCD8_LV * (1 - (eCD8_LV + pCD8_LV) / MAX_CD8_LV) *
        (Emax_IL2_CD8prol * IL2_LV / (IL2_LV + EC50_IL2_CD8prol)) *
        (1 - Imax_TGFb_CD8prol * TGFb_LV / (IC50_TGFb_CD8prol + TGFb_LV)) *
        (1 + f_Th1_CD8) * (1 - f_Treg_CD8)                                               # Eq. S14

    d/dt(pTh1_LV) <- -kdeath_pTh1 * pTh1_LV +
      kPL_LV_CD4 * pTh1_PL * (V_PL / V_LV) -
      pTh1_act_LV * pTh1_LV                                                              # Eq. S15

    d/dt(eTh1_LV) <- pTh1_act_LV * pTh1_LV -
      kdeath_eTh1 * eTh1_LV +
      kprol_Th1 * eTh1_LV * (1 - (eTh1_LV + pTh1_LV) / MAX_Th1_LV) *
        (Emax_IL2_Th1prol * IL2_LV / (IL2_LV + EC50_IL2_Th1prol)) *
        (1 - Imax_TGFb_Th1prol * TGFb_LV / (TGFb_LV + IC50_TGFb_Th1prol))                # Eq. S16

    d/dt(pTh2_LV) <- kPL_LV_CD4 * pTh2_PL * (V_PL / V_LV) -
      pTh2_act_LV * pTh2_LV -
      kdeath_pTh2 * pTh2_LV                                                              # Eq. S17

    d/dt(eTh2_LV) <- -kdeath_eTh2 * eTh2_LV +
      pTh2_act_LV * pTh2_LV +
      kprol_Th2 * eTh2_LV * (1 - (eTh2_LV + pTh2_LV) / MAX_Th2_LV) *
        (Emax_IL2_Th2prol * IL2_LV / (IL2_LV + EC50_IL2_Th2prol)) *
        (1 - Imax_TGFb_Th2prol * TGFb_LV / (TGFb_LV + IC50_TGFb_Th2prol))                # Eq. S18

    d/dt(pTreg_LV) <- kPL_LV_CD4 * pTreg_PL * (V_PL / V_LV) -
      pTreg_act_LV * pTreg_LV -
      kdeath_pTreg * pTreg_LV                                                            # Eq. S19

    d/dt(eTreg_LV) <- -kdeath_eTreg * eTreg_LV +
      kprol_Treg * eTreg_LV * (1 - (eTreg_LV + pTreg_LV) / MAX_Treg_LV) *
        (Emax_IL2_Tregprol * IL2_LV / (EC50_IL2_Tregprol + IL2_LV)) +
      pTreg_act_LV * pTreg_LV                                                            # Eq. S20

    # =====================================================================
    # 4. LIVER - cytokine signalling (Eq. S21-S29)
    # =====================================================================
    # Eq. S21 is the one cytokine balance in SM2 whose four production
    # terms carry no "* V_LV" factor (contrast Eq. S23, S25-S29), so the
    # outer 1 / V_LV divides them and IFN-gamma synthesis is 1500-fold
    # smaller than a dimensional reading would give. Transcribed exactly
    # as printed: simulating both readings head to head, the printed form
    # is closer to every reported target (peak HBV DNA 3.3e8 vs 4.5e7
    # IU/mL, hepatocyte loss 2.7% vs 0.5% against the paper's 10.8%,
    # peak ALT 343 vs 70 U/L, clearance below 10 IU/mL at 250 vs 345 days
    # against the paper's 173), so the rate constants were evidently
    # calibrated on this scale. See the vignette Errata.
    d/dt(IFNg_LV) <- (1 / V_LV) * kprod_IFNg_CD8 * CD8_IFNg_LV *
        (1 + exp(-kel_IL10_IFNg * IL10_LV)) *
        (1 - Imax_TGFb_IFNg * TGFb_LV / (IC50_TGFb_IFNg + TGFb_LV)) +
      (1 / V_LV) * kprod_IFNg_NKt * NK_TRAIL_LV *
        (1 + Emax_IL12_IFNg_NK * IL12_LV / (EC50_IL12_IFNg_NK + IL12_LV)) *
        (1 + exp(-kel_IL10_IFNg * IL10_LV)) -
      kdeg_IFNg * IFNg_LV -
      kLV_PL_IFNg * IFNg_LV +
      (1 / V_LV) * kprod_IFNg_Th1 * eTh1_LV *
        (1 + Emax_IL12_IFNg_Th1 * IL12_LV / (EC50_IL12_IFNg_Th1 + IL12_LV)) *
        (1 + exp(-kel_IL10_IFNg * IL10_LV)) +
      (1 / V_LV) * kprod_IFNg_mDCact * mDCa_LV *
        (1 + Emax_IL2_IFNg_mDC * IL2_LV / (EC50_IL2_IFNg_mDC + IL2_LV)) *
        (1 + exp(-kel_IL10_IFNg * IL10_LV)) +
      kPL_LV_IFNg * IFNg_PL * (V_PL / V_LV)                                              # Eq. S21

    # Eq. S22 uses kLV_PL_IFNa for both directions; both distribution
    # constants are 1/day so the two readings coincide numerically.
    d/dt(IFNa_LV) <- -kLV_PL_IFNa * IFNa_LV +
      kLV_PL_IFNa * IFNa_PL * (V_PL / V_LV)                                              # Eq. S22

    d/dt(TNFa_LV) <- kprod_TNFa_NKt * NK_TRAIL_LV -
      kLV_PL_TNFa * TNFa_LV -
      kdeg_TNFa * TNFa_LV +
      kprod_TNFa_mDCact * mDCa_LV *
        (1 + SLP_IFNg_TNFa * IFNg_LV) *
        (1 + SLP_IL12_TNFa * IL12_LV) *
        (1 + SLP_IL4_TNFa * IL4_LV) *
        (1 + Emax_IL2_TNFa * IL2_LV / (EC50_IL2_TNFa + IL2_LV)) *
        (1 - Imax_IL10_TNFa * IL10_LV / (IC50_IL10_TNFa + IL10_LV)) +
      kprod_TNFa_CD8 * eCD8_LV +
      kprod_TNFa_Th1 * eTh1_LV +
      kprod_TNFa_KCact * KCa_LV +
      kPL_LV_TNFa * TNFa_PL * (V_PL / V_LV)                                              # Eq. S23

    d/dt(TGFb_LV) <- kprod_TGFb_Treg * eTreg_LV +
      kprod_TGFb_mDCnaive * mDCn_LV -
      kdeg_TGFb * TGFb_LV -
      kdrain_TGFb * TGFb_LV                                                              # Eq. S24

    d/dt(IL10_LV) <- kprod_IL10_KCact * KCa_LV +
      kprod_IL10_Treg * eTreg_LV +
      kprod_IL10_Th1 * eTh1_LV -
      kdeg_IL10 * IL10_LV -
      kLV_PL_IL10 * IL10_LV +
      kprod_IL10_Th2 * eTh2_LV +
      kprod_IL10_mDCact * mDCa_LV *
        (1 + SLP_IFNg_IL10 * IFNg_LV) * (1 + SLP_IL4_IL10 * IL4_LV) +
      kprod_IL10_mDCnaive * mDCn_LV +
      kPL_LV_IL10 * IL10_PL * (V_PL / V_LV) -
      kdrain_IL10 * IL10_LV                                                              # Eq. S25

    d/dt(IL6_LV) <- kprod_IL6_mDCact * mDCa_LV *
        (1 + SLP_IL4_IL6 * IL4_LV) * (1 + SLP_IL10_IL6 * IL10_LV) -
      kdeg_IL6 * IL6_LV +
      kprod_IL6_KCnaive * KCn_LV +
      kprod_IL6_Th2 * eTh2_LV -
      kdrain_IL6 * IL6_LV                                                                # Eq. S26

    d/dt(IL4_LV) <- kprod_IL4_Th2 * eTh2_LV -
      kdeg_IL4 * IL4_LV +
      kprod_IL4_CD8 * eCD8_LV -
      kdrain_IL4 * IL4_LV                                                                # Eq. S27

    d/dt(IL2_LV) <- kprod_IL2_Th1 * eTh1_LV -
      kdeg_IL2 * IL2_LV +
      kprod_IL2_CD8 * eCD8_LV +
      kprod_IL2_mDCact * mDCa_LV -
      kdrain_IL2 * IL2_LV                                                                # Eq. S28

    d/dt(IL12_LV) <- -kdeg_IL12 * IL12_LV +
      kprod_IL12_KCact * KCa_LV +
      kprod_IL12_mDCact * mDCa_LV *
        (1 + SLP_IFNg_IL12 * IFNg_LV) *
        (1 + SLP_IL4_IL12 * IL4_LV) *
        (1 - Imax_TNFa_IL12 * TNFa_LV / (IC50_TNFa_IL12 + TNFa_LV)) *
        (1 + IC50_IL10_IL12 / (IC50_IL10_IL12 + IL10_LV)) -
      kdrain_IL12 * IL12_LV                                                              # Eq. S29

    # =====================================================================
    # 5. PLASMA - virus life cycle (Eq. S30-S34)
    # =====================================================================
    d/dt(HBV_PL) <- -(HBV_int_rate / V_PL) *
        (Hep_LV / (iHep1_LV + Hep_LV + iHep2_LV)) -
      kdeg_HBV_PL * HBV_PL +
      kLV_PL_HBV * expHBV_LV * (V_LV / V_PL) -
      kon_antiHBs * HBV_PL * antiHBs_PL +
      koff_antiHBs * cpxHBV_PL                                                           # Eq. S30

    d/dt(SVP_PL) <- ksyn_SVP_cccDNA * iHep1_LV * (1 - HBV_rep_inhibition) -
      kdeg_SVP_PL * SVP_PL -
      kon_antiHBs * SVP_PL * antiHBs_PL +
      koff_antiHBs * cpxSVP_PL +
      ksyn_SVP_iDNA * iHep2_LV                                                           # Eq. S31

    d/dt(HBeAg_PL) <- -kdeg_HBeAg_PL * HBeAg_PL +
      ksyn_HBeAg_cccDNA * iHep1_LV * (1 - HBV_rep_inhibition) -
      kon_antiHBe * antiHBe_PL * HBeAg_PL +
      koff_antiHBe * cpxHBeAg_PL                                                         # Eq. S32

    d/dt(HBcAg_PL) <- ksyn_HBcAg_cccDNA * iHep1_LV * (1 - HBV_rep_inhibition) -
      kdeg_HBcAg_PL * HBcAg_PL -
      kon_antiHBc * HBcAg_PL * antiHBc_PL +
      koff_antiHBc * cpxHBcAg_PL                                                         # Eq. S33

    d/dt(ALT_PL) <- -kdeg_ALT * ALT_PL +
      ksyn_ALT * (NK_lysis_rate_Hep + NK_lysis_rate_iHep1 +
                  NK_lysis_rate_iHep2 + CD8_lysis_rate_iHep1 +
                  CD8_lysis_rate_iHep2 +
                  V_LV * (kdeath_Hep * Hep_LV + kdeath_iHep * iHep1_LV +
                          kdeath_iHep * iHep2_LV)) / V_PL                                # Eq. S34

    # =====================================================================
    # 6. PLASMA - innate immune system (Eq. S35-S38)
    # =====================================================================
    d/dt(NKn_PL) <- -kPL_LV_NK * NKn_PL +
      ksyn_NK -
      kdeath_NKnaive * NKn_PL                                                            # Eq. S35

    d/dt(pDCn_PL) <- -pDC_activation * pDCn_PL +
      ksyn_pDC -
      kdeath_pDCnaive * pDCn_PL                                                          # Eq. S36

    d/dt(pDCa_PL) <- pDC_activation * pDCn_PL - kdeath_pDCact * pDCa_PL                  # Eq. S37

    d/dt(mDCn_PL) <- -kPL_LV_DC * mDCn_PL +
      ksyn_mDC -
      kdeath_mDCnaive * mDCn_PL                                                          # Eq. S38

    # =====================================================================
    # 7. PLASMA - adaptive immune system (Eq. S39-S49)
    # =====================================================================
    d/dt(pTh1_PL) <- kLN_PL_CD4 * pTh1_LN * (V_LN / V_PL) -
      kPL_LV_CD4 * pTh1_PL -
      kdeath_pTh1 * pTh1_PL                                                              # Eq. S39

    d/dt(pTh2_PL) <- kLN_PL_CD4 * pTh2_LN * (V_LN / V_PL) -
      kPL_LV_CD4 * pTh2_PL -
      kdeath_pTh2 * pTh2_PL                                                              # Eq. S40

    d/dt(pTreg_PL) <- -kPL_LV_CD4 * pTreg_PL +
      kLN_PL_CD4 * pTreg_LN * (V_LN / V_PL) -
      kdeath_pTreg * pTreg_PL                                                            # Eq. S41

    d/dt(pCD8_PL) <- kLN_PL_CD8 * pCD8_LN * (V_LN / V_PL) -
      kdeath_pCD8 * pCD8_PL -
      kPL_LV_CD8 * pCD8_PL                                                               # Eq. S42

    d/dt(antiHBs_PL) <- kprod_Ab_HBs * PCs_LN -
      kdeg_antiHBs * antiHBs_PL -
      kon_antiHBs * HBV_PL * antiHBs_PL -
      kon_antiHBs * SVP_PL * antiHBs_PL +
      koff_antiHBs * cpxSVP_PL +
      koff_antiHBs * cpxHBV_PL                                                           # Eq. S43

    d/dt(antiHBe_PL) <- kprod_Ab_HBe * PCe_LN * 2.7e-16 * 13.43 -
      kdeg_antiHBe * antiHBe_PL -
      kon_antiHBe * antiHBe_PL * HBeAg_PL +
      koff_antiHBe * cpxHBeAg_PL                                                         # Eq. S44

    d/dt(antiHBc_PL) <- kprod_Ab_HBc * PCc_LN -
      kdeg_antiHBc * antiHBc_PL -
      kon_antiHBc * HBcAg_PL * antiHBc_PL +
      koff_antiHBc * cpxHBcAg_PL                                                         # Eq. S45

    d/dt(cpxHBV_PL) <- kon_antiHBs * HBV_PL * antiHBs_PL -
      kdeg_complexHBV * cpxHBV_PL -
      koff_antiHBs * cpxHBV_PL                                                           # Eq. S46

    d/dt(cpxSVP_PL) <- kon_antiHBs * SVP_PL * antiHBs_PL -
      kdeg_complexHBsAg * cpxSVP_PL -
      koff_antiHBs * cpxSVP_PL                                                           # Eq. S47

    d/dt(cpxHBeAg_PL) <- -kdeg_complexHBeAg * cpxHBeAg_PL +
      kon_antiHBe * antiHBe_PL * HBeAg_PL -
      koff_antiHBe * cpxHBeAg_PL                                                         # Eq. S48

    d/dt(cpxHBcAg_PL) <- kon_antiHBc * HBcAg_PL * antiHBc_PL -
      koff_antiHBc * cpxHBcAg_PL -
      kdeg_complexHBcAg * cpxHBcAg_PL                                                    # Eq. S49

    # =====================================================================
    # 8. PLASMA - cytokine signalling (Eq. S50-S53)
    # =====================================================================
    d/dt(IFNg_PL) <- kLV_PL_IFNg * IFNg_LV * (V_LV / V_PL) -
      kPL_LV_IFNg * IFNg_PL                                                              # Eq. S50

    d/dt(IFNa_PL) <- kLV_PL_IFNa * IFNa_LV * (V_LV / V_PL) -
      kPL_LV_IFNa * IFNa_PL +
      kprod_IFNa_pDCact * pDCa_PL *
        (1 - HBsAg_PL / (HBsAg_PL + IC50_HBsAg_IFNa_pDC)) -
      kdeg_IFNa * IFNa_PL                                                                # Eq. S51

    d/dt(TNFa_PL) <- kLV_PL_TNFa * TNFa_LV * (V_LV / V_PL) -
      kPL_LV_TNFa * TNFa_PL                                                              # Eq. S52

    d/dt(IL10_PL) <- kLV_PL_IL10 * IL10_LV * (V_LV / V_PL) -
      kPL_LV_IL10 * IL10_PL                                                              # Eq. S53

    # =====================================================================
    # 9. LYMPH - innate immune system (Eq. S54)
    # =====================================================================
    d/dt(mDCa_LN) <- -kdeath_mDCact * mDCa_LN +
      kLV_LN_DC * mDCa_LV * (V_LV / V_LN)                                                # Eq. S54

    # =====================================================================
    # 10. LYMPH - T cells (Eq. S55-S61)
    # =====================================================================
    d/dt(CD8n_LN) <- -kdeath_CD8naive_LN * CD8n_LN -
      CD8_diff_LN * CD8n_LN +
      ksyn_CD8 +
      krec_DC * mDCa_LN                                                                  # Eq. S55

    # Eq. S56 writes the proliferation constant as kprol_CD8; Table S3
    # tabulates kprol_CD8_LN and kprol_CD8_LV and this state is in lymph.
    d/dt(pCD8_LN) <- CD8_diff_LN * CD8n_LN -
      kLN_PL_CD8 * pCD8_LN -
      ksyn_CD8m * pCD8_LN +
      kprol_CD8_LN * pCD8_LN * (1 - pCD8_LN / MAX_CD8_LN) *
        (Emax_IL2_CD8prol * IL2_LN / (IL2_LN + EC50_IL2_CD8prol)) *
        (1 - Imax_TGFb_CD8prol * TGFb_LN / (TGFb_LN + IC50_TGFb_CD8prol))                # Eq. S56

    d/dt(CD4n_LN) <- -kdeath_CD4naive_LN * CD4n_LN +
      ksyn_CD4 -
      total_CD4_diff * CD4n_LN +
      krec_DC * mDCa_LN                                                                  # Eq. S57

    d/dt(pTh1_LN) <- Th1_diff_rate * CD4n_LN -
      kLN_PL_CD4 * pTh1_LN +
      kprol_Th1 * pTh1_LN * (1 - pTh1_LN / MAX_Th1_LN) *
        (Emax_IL2_Th1prol * IL2_LN / (IL2_LN + EC50_IL2_Th1prol)) *
        (1 - Imax_TGFb_Th1prol * TGFb_LN / (TGFb_LN + IC50_TGFb_Th1prol))                # Eq. S58

    d/dt(pTh2_LN) <- Th2_diff_rate * CD4n_LN -
      kLN_PL_CD4 * pTh2_LN +
      kprol_Th2 * pTh2_LN * (1 - pTh2_LN / MAX_Th2_LN) *
        (Emax_IL2_Th2prol * IL2_LN / (IL2_LN + EC50_IL2_Th2prol)) *
        (1 - Imax_TGFb_Th2prol * TGFb_LN / (TGFb_LN + IC50_TGFb_Th2prol))                # Eq. S59

    d/dt(pTreg_LN) <- Treg_diff_rate * CD4n_LN -
      kLN_PL_CD4 * pTreg_LN +
      kprol_Treg * pTreg_LN * (1 - pTreg_LN / MAX_Treg_LN) *
        (Emax_IL2_Tregprol * IL2_LN / (IL2_LN + EC50_IL2_Tregprol))                      # Eq. S60

    d/dt(TFH_LN) <- TFH_diff_rate * CD4n_LN +
      kprol_TFH * TFH_LN * (1 - TFH_LN / MAX_TFH_LN) *
        (Emax_IL21_TFHprol * IL21_LN / (IL21_LN + EC50_IL21_TFHprol)) -
      kdeath_TFH * TFH_LN                                                                # Eq. S61

    # =====================================================================
    # 11. LYMPH - anti-HBs B-cell lineage (Eq. S62-S68)
    # =====================================================================
    d/dt(BnHBs_LN) <- -HBs_PB_act_rate * BnHBs_LN +
      ksyn_Bcell -
      kdeath_Bnaive_LN * BnHBs_LN                                                        # Eq. S62

    d/dt(PBs1_LN) <- HBs_PB_act_rate * BnHBs_LN -
      kdeath_plasmablasts * PBs1_LN -
      PB_transit * PBs1_LN +
      PB_prol * PBs1_LN * (1 - PBs1_LN / MAX_PB_LN)                                      # Eq. S63

    d/dt(PBs2_LN) <- PB_transit * PBs1_LN -
      kdeath_plasmablasts * PBs2_LN -
      PB_transit * PBs2_LN                                                               # Eq. S64

    d/dt(PBs3_LN) <- -kdeath_plasmablasts * PBs3_LN +
      PB_transit * PBs2_LN -
      PB_transit * PBs3_LN                                                               # Eq. S65

    d/dt(PBs4_LN) <- -kdeath_plasmablasts * PBs4_LN +
      PB_transit * PBs3_LN -
      PB_transit * PBs4_LN                                                               # Eq. S66

    d/dt(PBs5_LN) <- -kdeath_plasmablasts * PBs5_LN +
      PB_transit * PBs4_LN -
      PB_transit * PBs5_LN                                                               # Eq. S67

    d/dt(PCs_LN) <- -kdeath_Lplasmacells * PCs_LN +
      PB_transit * PBs5_LN                                                               # Eq. S68

    # =====================================================================
    # 12. LYMPH - anti-HBe B-cell lineage (Eq. S69-S75)
    # =====================================================================
    d/dt(BnHBe_LN) <- -HBe_PB_act_rate * BnHBe_LN +
      ksyn_Bcell -
      kdeath_Bnaive_LN * BnHBe_LN                                                        # Eq. S69

    d/dt(PBe1_LN) <- HBe_PB_act_rate * BnHBe_LN -
      kdeath_plasmablasts * PBe1_LN +
      PB_prol * PBe1_LN * (1 - PBe1_LN / MAX_PB_LN) -
      PB_transit * PBe1_LN                                                               # Eq. S70

    d/dt(PBe2_LN) <- PB_transit * PBe1_LN -
      kdeath_plasmablasts * PBe2_LN -
      PB_transit * PBe2_LN                                                               # Eq. S71

    d/dt(PBe3_LN) <- -kdeath_plasmablasts * PBe3_LN +
      PB_transit * PBe2_LN -
      PB_transit * PBe3_LN                                                               # Eq. S72

    d/dt(PBe4_LN) <- -kdeath_plasmablasts * PBe4_LN +
      PB_transit * PBe3_LN -
      PB_transit * PBe4_LN                                                               # Eq. S73

    d/dt(PBe5_LN) <- -PB_transit * PBe5_LN -
      kdeath_plasmablasts * PBe5_LN +
      PB_transit * PBe4_LN                                                               # Eq. S74

    # Eq. S75 is the only plasma-cell state to use the short-lived death
    # constant; Eq. S68 and Eq. S82 use the long-lived one.
    d/dt(PCe_LN) <- PB_transit * PBe5_LN -
      kdeath_Splasmacells * PCe_LN                                                       # Eq. S75

    # =====================================================================
    # 13. LYMPH - anti-HBc B-cell lineage (Eq. S76-S82)
    # =====================================================================
    d/dt(BnHBc_LN) <- -HBc_PB_act_rate * BnHBc_LN +
      ksyn_Bcell -
      kdeath_Bnaive_LN * BnHBc_LN                                                        # Eq. S76

    d/dt(PBc1_LN) <- -kdeath_plasmablasts * PBc1_LN +
      HBc_PB_act_rate * BnHBc_LN -
      PB_transit * PBc1_LN +
      PB_prol * PBc1_LN * (1 - PBc1_LN / MAX_PB_LN)                                      # Eq. S77

    d/dt(PBc2_LN) <- PB_transit * PBc1_LN -
      kdeath_plasmablasts * PBc2_LN -
      PB_transit * PBc2_LN                                                               # Eq. S78

    d/dt(PBc3_LN) <- PB_transit * PBc2_LN -
      PB_transit * PBc3_LN -
      kdeath_plasmablasts * PBc3_LN                                                      # Eq. S79

    d/dt(PBc4_LN) <- PB_transit * PBc3_LN -
      PB_transit * PBc4_LN -
      kdeath_plasmablasts * PBc4_LN                                                      # Eq. S80

    d/dt(PBc5_LN) <- PB_transit * PBc4_LN -
      PB_transit * PBc5_LN -
      kdeath_plasmablasts * PBc5_LN                                                      # Eq. S81

    d/dt(PCc_LN) <- -kdeath_Lplasmacells * PCc_LN +
      PB_transit * PBc5_LN                                                               # Eq. S82

    # =====================================================================
    # 14. LYMPH - cytokine signalling (Eq. S83-S89)
    # =====================================================================
    d/dt(IL12_LN) <- kprod_IL12_mDCact * mDCa_LN -
      kdeg_IL12 * IL12_LN +
      kdrain_IL12 * IL12_LV * (V_LV / V_LN)                                              # Eq. S83

    d/dt(IL4_LN) <- kprod_IL4_Th2 * pTh2_LN -
      kdeg_IL4 * IL4_LN +
      kprod_IL4_CD8 * pCD8_LN +
      kdrain_IL4 * IL4_LV * (V_LV / V_LN)                                                # Eq. S84

    d/dt(TGFb_LN) <- kprod_TGFb_Treg * pTreg_LN -
      kdeg_TGFb * TGFb_LN +
      kdrain_TGFb * TGFb_LV * (V_LV / V_LN)                                              # Eq. S85

    d/dt(IL21_LN) <- kprod_IL21_TFH * TFH_LN -
      kdeg_IL21 * IL21_LN +
      kprod_IL21_Th1 * pTh1_LN +
      kprod_IL21_Th2 * pTh2_LN                                                           # Eq. S86

    d/dt(IL6_LN) <- kprod_IL6_mDCact * mDCa_LN -
      kdeg_IL6 * IL6_LN +
      kprod_IL6_Th2 * pTh2_LN +
      kdrain_IL6 * IL6_LV * (V_LV / V_LN)                                                # Eq. S87

    d/dt(IL2_LN) <- kprod_IL2_Th1 * pTh1_LN -
      kdeg_IL2 * IL2_LN +
      kprod_IL2_CD8 * pCD8_LN +
      kprod_IL2_mDCact * mDCa_LN +
      kdrain_IL2 * IL2_LV * (V_LV / V_LN)                                                # Eq. S88

    d/dt(IL10_LN) <- -kdeg_IL10 * IL10_LN +
      kprod_IL10_Th2 * pTh2_LN +
      kprod_IL10_Th1 * pTh1_LN +
      kprod_IL10_Treg * pTreg_LN +
      kprod_IL10_mDCact * mDCa_LN +
      kdrain_IL10 * IL10_LV * (V_LV / V_LN)                                              # Eq. S89

    # =====================================================================
    # 15. Reported (clinical-scale) outputs, SM3 Table S4 Notes
    # =====================================================================
    HBV_nM_PL    <- HBV_PL / NAvo * 1e12                                                 # T4 Notes, HBV_nM_PL (nM)
    HBV_DNA_IU   <- HBV_PL * 0.2                                                         # T4 Notes, HBV DNA IU_PL (IU/mL)
