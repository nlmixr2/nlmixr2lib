    antiHBs_mIU  <- antiHBs_PL * 2.7e-16 * 13.43 * 1e3                                   # T4 Notes, AntiHBs IU_PL (mIU/mL)
    antiHBe_mIU  <- antiHBe_PL * 1e3                                                     # T4 Notes, AntiHBe IU_PL (mIU/mL)
    antiHBc_mIU  <- antiHBc_PL * 2.7e-16 * 13.43 * 1e3                                   # T4 Notes, AntiHBc IU_PL (mIU/mL)
    ALT_UL       <- ALT_PL * 1e3                                                         # ALT (U/L) = ALT_PL (IU/mL) * 1000
    TotalHep_LV  <- Hep_LV + iHep1_LV + iHep2_LV                                         # SM1 Table S2, TotalHep
    SVP_excess   <- SVP_PL / max(1e-30, HBV_PL)                                          # simulated SVP : virion ratio

    # =====================================================================
    # 15b. Reported constants that no published equation consumes
    #
