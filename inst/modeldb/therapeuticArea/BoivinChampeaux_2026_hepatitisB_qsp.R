    chk_kdrain_TGFb   <- kdeg_TGFb * ratio_TGFb_LyL - kdrain_TGFb                        # ~0 (0.21851 vs 0.2186)
    # Equilibrium NTCP occupancy implied by KD_HBV and NTCP. The paper's
    # LSA (Figure 5) ranks KD_HBV and NTCP among the most influential
    # parameters for HBV DNA, but no published equation links them to
    # pct_bound_HBV, which HBV_int_rate uses directly, and the two
    # readings disagree. This residual is NOT zero. See vignette Errata.
    chk_pct_bound_HBV <- NTCP / (NTCP + KD_HBV) - pct_bound_HBV                          # 0.0833 (0.3333 vs 0.25)
    # Reported SVP : virion fold excess, for comparison with SVP_excess.
    chk_SVP_excess    <- f_SVP_HBV                                                       # T3 f_SVP_HBV = 100

